#!/bin/sh
# ═══ สลับไฟล์เว็บที่อัปไว้ขึ้นเป็นของจริง — กดซ้ำแล้วไม่พัง ═══
#
# ★★ ทำไมต้องมีไฟล์นี้ (6 พ.ย. 2569)
#   เดิมใช้คำสั่งยาวบรรทัดเดียว `mv dist dist-old-DATE && mv dist-new dist`
#   วันนั้นมันถูกกดซ้ำหลังจากรันสำเร็จไปแล้ว ผลคือ
#     ขั้นแรก  ย้าย dist ออกไป **สำเร็จ**
#     ขั้นสอง  ล้ม เพราะ dist-new ถูกใช้ไปแล้วตั้งแต่รอบก่อน
#   เว็บจึงไม่เหลือไฟล์ให้เสิร์ฟและตอบ 404 อยู่พักหนึ่ง
#   ซ้ำร้าย `dist-old-DATE` มีอยู่แล้ว `mv` จึงไม่ได้เขียนทับ แต่**ย้ายเข้าไปซ้อนข้างใน**
#   กลายเป็น dist-old-DATE/dist ซึ่งหาไม่เจอถ้าไม่รู้ว่าเกิดอะไรขึ้น
#
#   RUNBOOK เขียนกติกานี้ไว้เองตั้งแต่ 28 ต.ค. 2569 ว่า
#   **"คำสั่งทำลายต้องไม่อยู่ในที่ที่กดได้ง่ายกว่าที่ควร"** แต่ยังพลาดซ้ำ
#   ➜ เลยเปลี่ยนจาก "คำสั่งที่ต้องกดให้ถูกจังหวะ" เป็น "สคริปต์ที่ตรวจให้เองก่อนแตะอะไร"
#
# ★ หลักของไฟล์นี้: **ไม่มีของใหม่ = ไม่ใช่ความผิดพลาด** แค่บอกแล้วจบด้วยรหัส 0
#   กดกี่ครั้งก็ได้ ครั้งที่สองเป็นต้นไปจะไม่ทำอะไรเลย
#
# ใช้:  sh ops/deploy-swap.sh
#   (อัปไฟล์ขึ้นที่พักก่อนด้วย  scp -r dist root@100.102.230.64:/home/dev/dist-new)
set -eu

BOX="${BOX:-root@100.102.230.64}"
SITE="${SITE:-https://mew.plotnexuslab.com}"

echo "═══ สลับของใหม่ขึ้นเว็บจริง ═══"

LOCAL_BUNDLE=$(grep -oE 'main-[A-Za-z0-9_-]+\.js' dist/index.html 2>/dev/null | head -1 || true)
[ -n "$LOCAL_BUNDLE" ] && echo "บันเดิลในเครื่อง: $LOCAL_BUNDLE"

# ── ตรวจและสลับในคำสั่งเดียวบนกล่อง ──
# ★ ต้องทำบนกล่องรวดเดียว ไม่ใช่ตรวจจากเครื่องนี้แล้วค่อยสั่งย้าย
#   เพราะระหว่างสองคำสั่งสถานะเปลี่ยนได้ (เจอมาแล้วตอนกู้เว็บคาบเกี่ยวกับคนกดซ้ำ)
ssh -o ConnectTimeout=25 "$BOX" 'sh -s' < ops/deploy-swap-remote.sh

# ── ตรวจผลจากฝั่งผู้ใช้จริง ──
echo ""
echo "═══ ตรวจหลังสลับ ═══"
CODE=$(curl -s --max-time 25 -o /dev/null -w '%{http_code}' "$SITE/" || echo 000)
LIVE=$(curl -s --max-time 25 "$SITE/" | grep -oE 'main-[A-Za-z0-9_-]+\.js' | head -1 || true)
API=$(curl -s --max-time 20 -o /dev/null -w '%{http_code}' "$SITE/api/health" || echo 000)
printf 'เว็บจริง   %s\nบันเดิล    %s\nAPI health %s\n' "$CODE" "${LIVE:-อ่านไม่ได้}" "$API"

if [ "$CODE" != "200" ]; then
  echo ""
  echo "★★ เว็บไม่ตอบ 200 — ดูว่า /home/dev/dist มีอยู่ไหมก่อนทำอย่างอื่น"
  echo "    ถ้าหาย ของเดิมอยู่ใน dist-old-* ตัวล่าสุด ย้ายกลับมาเป็น dist ได้เลย"
  exit 1
fi

if [ -n "$LOCAL_BUNDLE" ] && [ -n "$LIVE" ] && [ "$LOCAL_BUNDLE" != "$LIVE" ]; then
  echo ""
  echo "★ บันเดิลบนเว็บไม่ตรงกับที่ build ไว้ในเครื่อง — อาจยังไม่ได้ scp ของใหม่ขึ้นไป"
  exit 1
fi

echo ""
echo "เรียบร้อย ★ เปิดหน้าจริงดูด้วยตาอีกที ชื่อไฟล์ตรงพิสูจน์แค่ว่าไฟล์ถูกวางแล้ว"
