import { AppError } from "../lib/error.js";

/** ชื่อทางส่งที่โค้ดนี้รู้จัก */
export const TRANSPORTS = ["hold", "outbox", "mqtt", "http"];

export const transportName = () => (process.env.CONTROL_TRANSPORT || "hold").trim();

/** ส่งคำสั่งออกได้จริงหรือยัง — หน้าเว็บใช้ค่านี้บอกคนกดว่ากดแล้วจะเกิดอะไร */
export const canSend = () => transportName() !== "hold";

/**
 * ★ `outbox` ต่างจาก `hold` ตรงที่ **มีคนมารับ** (T1.310)
 *   hold   = ตรวจผ่านด่านแล้ว แต่ไม่มีทางส่งเลย คำสั่งจะค้างอยู่อย่างนั้น
 *   outbox = คำสั่งรออยู่ในกล่องขาออก Node-RED จะมาดึงไปส่งให้ PLC
 * สองอันนี้ใช้สถานะ `held` เหมือนกันในฐาน แต่แยกกันด้วยคอลัมน์ `transport`
 */
export const isOutbox = () => transportName() === "outbox";

/**
 * ส่งคำสั่งออก
 * @returns {Promise<{status: "held"|"sent", detail: string}>}
 *          held = ผ่านด่านแล้วแต่ยังไม่มีทางส่ง · sent = ปล่อยออกไปแล้ว
 *          **sent ไม่ได้แปลว่าตู้ทำตาม** ยืนยันผลต้องรอช่องทางตอบกลับที่ยังไม่มี
 */
export async function sendCommand(cmd, device) {
  const kind = transportName();

  if (kind === "hold") {
    return {
      status: "held",
      detail: "ยังไม่มีสิทธิ์ส่งเข้าระบบฟาร์ม — เก็บไว้ในคิวแล้ว",
    };
  }

  if (kind === "outbox") {
    /* ★ ไม่บังคับว่าต้องมี remote_addr ในทางนี้ — **ตัวแปลงไปเป็นภาษา PLC อยู่ใน Node-RED**
       ซึ่งเป็นเหตุผลที่เลือกทางนี้ตั้งแต่แรก ถ้าในฐานมีที่อยู่ก็ส่งไปให้ใช้ก่อน
       ถ้าไม่มี Node-RED ต้องแปลงจาก deviceId เอง (ดู server/src/control/outbox.js) */
    return {
      status: "held",
      detail: "อยู่ในกล่องขาออกแล้ว รอ Node-RED มารับไปส่งให้ตู้ควบคุม",
    };
  }

  if (kind === "mqtt" || kind === "http") {
    /* ถึงจะตั้ง CONTROL_TRANSPORT ไว้ ก็ยังส่งไม่ได้ถ้าไม่มีที่อยู่ปลายทางของอุปกรณ์นั้น
       ที่อยู่ต้องมาจากเจ้าของระบบ แล้วกรอกลง control_device.remote_addr */
    if (!device?.remote_addr)
      throw new AppError(
        503,
        "no_remote_addr",
        `${cmd.deviceId} ยังไม่มีที่อยู่ปลายทาง (control_device.remote_addr) — ` +
          "ต้องได้สเปกจากเจ้าของระบบก่อน",
      );

    throw new AppError(
      501,
      "transport_not_built",
      `ยังไม่ได้เขียนตัวส่งแบบ ${kind} — ต้องได้สเปก topic/payload จากเจ้าของระบบก่อน ` +
        "เขียนโดยเดาเองไม่ได้ (ดู docs/RUNBOOK.md หัวข้อ ส่งคำสั่งไปตู้ควบคุม)",
    );
  }

  throw new AppError(
    500,
    "bad_transport",
    `CONTROL_TRANSPORT=${kind} ไม่รู้จัก — ใช้ได้: ${TRANSPORTS.join(" · ")}`,
  );
}
