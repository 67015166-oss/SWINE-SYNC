/** แปลงได้แค่สามวิธีนี้ — ห้ามเปิดกว้างกว่านี้ */
const ALLOWED = new Set(["PUT", "PATCH", "DELETE"]);

/** ชื่อหัวคำขอที่ใช้บอกวิธีจริง (ชื่อเดียวกับที่ฝั่งหน้าเว็บส่ง) */
export const OVERRIDE_HEADER = "x-http-method-override";

/**
 * ★ แปลงเฉพาะคำขอที่เข้ามาเป็น POST — วิธีอื่นปล่อยผ่านตามเดิม
 *   ถ้าแปลงจากวิธีไหนก็ได้ GET ที่แนบหัวนี้มาจะกลายเป็นคำสั่งลบข้อมูลทันที
 */
export function methodOverride(req, _res, next) {
  if (req.method === "POST") {
    const raw = typeof req.get === "function" ? req.get(OVERRIDE_HEADER) : req.headers?.[OVERRIDE_HEADER];
    const want = String(raw ?? "").trim().toUpperCase();
    if (ALLOWED.has(want)) req.method = want;
  }
  next();
}
