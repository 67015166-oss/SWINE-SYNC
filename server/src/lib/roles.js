/** เรียงจากต่ำไปสูง — ขั้นสูงกว่าทำสิ่งที่ขั้นต่ำกว่าทำได้เสมอ */
export const ROLES = ["viewer", "editor", "operator", "admin"];

/** ชื่อไทยของแต่ละระดับ สำหรับข้อความที่ผู้ใช้เห็น */
export const ROLE_NAME = {
  viewer: "ผู้ชม",
  editor: "ผู้บันทึก",
  operator: "ผู้ควบคุมอุปกรณ์",
  admin: "ผู้ดูแลระบบ",
};

/**
 * ระดับของบัญชีนี้อย่างน้อยเท่ากับ `min` ไหม
 *
 * ★ **ระดับที่ไม่รู้จักถือว่าต่ำกว่าทุกขั้น** — ค่าแปลก ๆ ในฐาน (หรือ null)
 *   ต้องไม่กลายเป็นสิทธิ์สูงโดยบังเอิญ ปลอดภัยไว้ก่อนเสมอ
 *   (`indexOf` คืน -1 ซึ่งน้อยกว่าทุก index จึงได้พฤติกรรมนี้มาฟรี แต่เขียนไว้ให้ชัด)
 */
export const roleAtLeast = (user, min) => ROLES.indexOf(user?.role) >= ROLES.indexOf(min);
