export function detectIntent(text) {
  const t = String(text ?? "").toLowerCase().replace(/\s+/g, "");
  if (!t) return "help";
  /* ★ เทียบตรงทั้งข้อความก่อนวนตาราง — ดู BARE_QUESTIONS ว่าทำไมไม่ใช้ includes */
  if (BARE_QUESTIONS.has(t)) return "ambiguous";
  for (const [intent, words] of INTENTS) {
    if (words.some((w) => t.includes(w.toLowerCase().replace(/\s+/g, "")))) return intent;
  }
  return "unknown";
}

/**
 * ข้อมูลที่ติดมากับปุ่มในการ์ด (postback) — รูปแบบ `a=<การกระทำ>&c=<รหัส>`
 * ใช้ของมาตรฐาน URLSearchParams จะได้ไม่ต้องคิดเรื่องอักขระพิเศษเอง
 */
export const postbackData = (action, code) =>
  new URLSearchParams({ a: action, c: code ?? "" }).toString();

export function parsePostback(data) {
  const p = new URLSearchParams(String(data ?? ""));
  const action = p.get("a");
  return action ? { action, code: p.get("c") || null } : null;
}

