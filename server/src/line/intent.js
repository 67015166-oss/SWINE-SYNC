/**
 * ★★ ในข้อความนี้มีคำสั่งอีกอันตามมาไหม (T1.326)
 *
 * เจอของจริง 9 ต.ค. 2569 — ผู้ใช้ส่งมาบรรทัดเดียวว่า
 *   `ตาย 1          ให้อาหาร 200          ยกเลิก`
 * ระบบบันทึกแค่ `ตาย 1` แล้ว **ทิ้งที่เหลือไปเงียบ ๆ** ผู้ใช้เข้าใจว่าบันทึกครบสามอย่าง
 *
 * ★ อันตรายตรงที่เงียบ — "ตาย 1 ย้ายออก 50" ที่บันทึกแค่อันแรก ทำให้จำนวนสุกรผิด
 *   โดยหน้าจอดูปกติทุกอย่าง ซึ่งเป็นกับดักเดียวกับที่ไล่แก้มาทั้งสัปดาห์
 *
 * ★ ไม่รับหลายคำสั่งในข้อความเดียวโดยเจตนา — การแยกคำสั่งจากข้อความยาว ๆ
 *   ต้องเดาขอบเขตของแต่ละอัน เดาผิดแล้วบันทึกผิดจำนวนหรือผิดชนิด
 *   **บอกให้พิมพ์ทีละคำสั่งชัดเจนกว่าและไม่มีทางเดาผิด**
 *
 * ตรวจแค่ "มีคำสั่งอื่นอยู่ในส่วนที่เหลือไหม" ไม่ได้พยายามแยกว่าเป็นคำสั่งอะไรบ้าง
 */
function hasAnotherCommand(rest) {
  const flat = String(rest ?? "").toLowerCase().replace(/\s+/g, "");
  if (!flat) return false;
  for (const [, words] of RECORD_WORDS) {
    for (const w of words) if (flat.includes(w.toLowerCase())) return true;
  }
  /* ★ รวมคำสั่งถอนด้วย — กรณีจริงที่เจอมี "ยกเลิก" ต่อท้ายแล้วหายไปเฉย ๆ */
  return UNDO_WORDS.some((w) => flat.includes(w.toLowerCase()));
}

