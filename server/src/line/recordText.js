/**
 * ค่าไฟตอนนี้ — มิเตอร์ส่งแรงดัน กระแส 3 เฟส ความถี่ กำลังไฟ และหน่วยสะสมมาจริง
 *
 * ★★ **ห้ามบวกกระแสสามเฟสเข้าด้วยกัน** ต่างเฟสกัน 120° บวกเลขตรง ๆ ไม่มีความหมาย
 *   (กติกาเดียวกับที่หน้าเว็บยึดไว้ ดู serverFarms.js `electricalOf`)
 *
 * ★ บอกเวลาที่เริ่มนับของ "วันนี้" ด้วย — ถ้าเริ่มเก็บตอนสาย ตัวเลขไม่ครอบคลุมทั้งวัน
 *   ไม่บอกแล้วคนอ่านจะนึกว่าฟาร์มใช้ไฟแค่นั้นจริง ๆ
 *
 * ★ **ไม่แปลงเป็นบาท** เพราะค่าไฟต่อหน่วยยังไม่ได้ตั้งไว้ที่ฝั่งเซิร์ฟเวอร์
 *   เลขบาทที่คิดจากอัตราสมมติดูน่าเชื่อแต่ผิด ซึ่งแย่กว่าไม่บอก
 */
export function powerText(r, scopeText) {
  if (!r) return `ยังไม่มีค่าจากมิเตอร์ไฟของ${scopeText ? ` ${scopeText}` : "โรงเรือนนี้"}ครับ`;
  const n1 = (v) => (v == null ? "—" : Number(v).toFixed(1));
  const amps = [r.current_a, r.current_b, r.current_c].filter((v) => v != null).map((v) => Number(v).toFixed(1));
  const lines = [
    `ค่าไฟตอนนี้ · ${scopeText}`,
    "",
    `กำลังไฟ ${n1(r.power_kw)} kW`,
    `แรงดัน ${n1(r.voltage)} V · ความถี่ ${n1(r.frequency)} Hz`,
    amps.length ? `กระแสแต่ละเฟส ${amps.join(" / ")} A` : null,
  ];
  if (r.today_kwh != null) {
    lines.push("", `ใช้ไปวันนี้ ${n1(r.today_kwh)} หน่วย`);
    if (r.today_from) {
      const t = new Date(r.today_from).toLocaleTimeString("th-TH", { hour: "2-digit", minute: "2-digit", timeZone: "Asia/Bangkok" });
      lines.push(`(เริ่มนับ ${t} น.)`);
    }
  }
  if (r.month_kwh != null) lines.push(`เดือนนี้ ${n1(r.month_kwh)} หน่วย`);
  return lines.filter((l) => l !== null).join("\n");
}

