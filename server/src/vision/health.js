/** ไม่มีผลประมวลผลใหม่นานกว่านี้ ถือว่า "ไม่ได้เห็นสุกรช่วงนี้" ไม่ใช่ "พัง" */
export const FRESH_SEC = 600;

/**
 * ★★ "ไม่มีผลประมวลผล" ≠ "พัง"
 *
 * ถ้าไม่มีสุกรเดินผ่านกล้อง ระบบจะไม่เขียนผลน้ำหนักลงฐานเลย ซึ่งถูกต้องแล้ว
 * ถ้าตีว่าเงียบ = พัง หน้าจอจะขึ้นแดงทั้งคืนทุกคืนจนคนเลิกเชื่อป้ายสถานะ
 * — บทเรียนเดียวกับตอนตั้งเกณฑ์แจ้งเตือนไลน์ว่า "ส่งเฉพาะวิกฤต" แล้วเงียบไปทั้งเดือน
 *
 * จึงแยกเป็นสามสถานะ ไม่ใช่สอง: ทำงาน · ว่าง · เสีย
 *
 * @param {object} o
 * @param {boolean} o.reachable ต่อถึงกล่องกล้องไหม
 * @param {number|null} o.fps เฟรมต่อวินาทีที่เขารายงาน
 * @param {number|null} o.lastEstimateAgeSec ผลประมวลผลล่าสุดเก่ากี่วินาที (null = ไม่รู้)
 * @returns {{state:"working"|"idle"|"down"|"unknown", why:string}}
 */
export function aiVerdict({ reachable, fps, lastEstimateAgeSec }) {
  if (!reachable) return { state: "down", why: "ต่อกล่องกล้องไม่ได้" };
  if (fps == null) return { state: "unknown", why: "กล้องตอบ แต่ไม่ได้บอกความเร็วภาพ" };
  /* ตอบ 200 แต่ fps เป็นศูนย์ = เซิร์ฟเวอร์ยังอยู่ แต่สายประมวลผลหยุดเดิน
     นี่คือเคสที่ /api/health ของเขาจับไม่ได้ และเป็นเหตุผลที่ไฟล์นี้มีอยู่ */
  if (fps <= 0) return { state: "down", why: "กล้องตอบ แต่ไม่ได้ประมวลผลภาพ" };
  if (lastEstimateAgeSec == null) return { state: "unknown", why: "อ่านประวัติจากคลังข้อมูลไม่ได้" };
  if (lastEstimateAgeSec <= FRESH_SEC) return { state: "working", why: "ประมวลผลอยู่" };
  return { state: "idle", why: "ประมวลผลอยู่ แต่ยังไม่พบสุกรในภาพช่วงที่ผ่านมา" };
}

/** ป้ายไทยของแต่ละสถานะ — ต้องมีข้อความเสมอ ห้ามสื่อด้วยสีอย่างเดียว */
export const AI_STATE_LABEL = {
  working: "กำลังประมวลผล",
  idle: "ว่าง",
  down: "ขัดข้อง",
  unknown: "ไม่ทราบสถานะ",
};

/**
 * ผลประมวลผลล่าสุดเก่ากี่วินาที — รับแถวจาก `/weights` ของคลังข้อมูล
 *
 * ★ **ห้ามเชื่อว่าแถวแรกใหม่ที่สุด** เขาเรียงมาให้ก็จริง แต่ถ้าวันหนึ่งเขาเปลี่ยนลำดับ
 *   เลขอายุจะเพี้ยนเงียบ ๆ โดยไม่มีอะไรพัง จึงหาค่ามากที่สุดเองทุกครั้ง
 */
export function lastEstimateAgeSec(rows, now = Date.now()) {
  if (!Array.isArray(rows) || rows.length === 0) return null;
  let newest = null;
  for (const r of rows) {
    const t = Date.parse(r?.estimated_at ?? "");
    if (Number.isFinite(t) && (newest === null || t > newest)) newest = t;
  }
  return newest === null ? null : Math.max(0, Math.round((now - newest) / 1000));
}

/**
 * ★ "เห็นในภาพตอนนี้" กับ "สุทธิจากการเดินผ่านเส้นนับ" เป็นคนละเลข
 *
 * ทีมกล้องย้ำข้อนี้มาเอง และมันสำคัญเพราะสองเลขนี้ตอบคนละคำถาม
 *   · `inFrame` = ตอนนี้กล้องเห็นกี่ตัว (ขึ้นลงตลอด ไม่ใช่จำนวนสุกรในเล้า)
 *   · `net`     = เข้าหักออกสะสม (ใช้ดูการเคลื่อนย้าย ไม่ใช่จำนวนที่เห็น)
 * เอาไปปนกันเมื่อไหร่ ตัวเลขฝูงสุกรบนหน้าจอจะผิดทันทีโดยไม่มีใครรู้
 */
export function pigCounts(data) {
  const c = data?.pig_counts ?? {};
  const n = (v) => (Number.isFinite(Number(v)) ? Number(v) : null);
  return { inFrame: n(c.total), in: n(c.in), out: n(c.out), net: n(c.net) };
}
