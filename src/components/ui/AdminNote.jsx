import Icon from "./Icon.jsx";
import { useT } from "../../lib/i18n/useT.js";
import { minRoleFor } from "../../lib/auth/roles.js";
import "./ui.css";

export default function AdminNote({ children, action }) {
  const t = useT();

  return (
    <p className="admin-note" role="note">
      <Icon name="lock" size={17} aria-hidden="true" />
      <span>
        <b>
          {action && minRoleFor(action).id !== "admin"
            ? t("ต้องมีสิทธิ์ระดับ{role}ขึ้นไป", { role: t(minRoleFor(action).name) })
            : t("ต้องมีสิทธิ์ผู้ดูแลระบบ")}
        </b>
        {children ? <> — {children}</> : null}
      </span>
    </p>
  );
}
