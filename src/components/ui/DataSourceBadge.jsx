import Icon from "./Icon.jsx";
import { useT } from "../../lib/i18n/useT.js";
import "./ui.css";

/**
 * ป้ายบอกที่มาของข้อมูล — "ข้อมูลจริง" (ต่อเซนเซอร์อยู่) · "จริง + ตัวอย่าง" · "ข้อมูลตัวอย่าง"
 *
 * ทำไมต้องมี: ตอนนี้มีเซนเซอร์จริงอยู่ฟาร์มเดียว ที่เหลือเป็นข้อมูลสมมติ
 * ถ้าไม่ติดป้าย คนดูจะแยกไม่ออกว่าตัวเลขไหนเอาไปตัดสินใจได้
 * (ตกลงกับผู้ใช้ 24 ส.ค. 2026 — เก็บข้อมูลตัวอย่างไว้ แต่ต้องบอกให้ชัด)
 *
 * **`mixed` เพิ่มมาเพราะกล่องสรุปหน้าภาพรวมเป็นตัวเลขรวมทุกฟาร์ม** (24 ก.ย. 2569)
 * เลขรวมที่มีทั้งฟาร์มจริงและฟาร์มตัวอย่างอยู่ในก้อนเดียวกัน จะติดป้ายว่า "ข้อมูลจริง" ก็เกินจริง
 * ติดว่า "ข้อมูลตัวอย่าง" ก็ไม่ตรง — ดู `blendSource` ใน lib/records/dataSource.js
 *
 * มีทั้งไอคอนและข้อความเสมอ เหมือน StatusBadge — ห้ามสื่อด้วยสีอย่างเดียว
 * `mixed` ใช้ไอคอนเดียวกับ `demo` โดยตั้งใจ เพราะสิ่งที่ต้องระวังเป็นเรื่องเดียวกัน
 * (มีเลขสมมติปนอยู่) ตัวที่บอกว่าปนมากน้อยแค่ไหนคือข้อความ ไม่ใช่ไอคอน
 *
 * **`local` เพิ่มมาตอนหน้าภาพรวมอ่านจำนวนสุกรจากบันทึกจริง** (T1.338)
 * เลขที่คนกรอกไว้ตอนยังไม่เข้าสู่ระบบอยู่แค่ในเครื่องนี้ — ไม่ใช่ข้อมูลตัวอย่าง (คนกรอกเองจริง ๆ)
 * แต่ก็ไม่ใช่ข้อมูลจริงของระบบ (เครื่องอื่นไม่เห็น) ยุบไปเป็นสองป้ายเดิมแล้วผิดทั้งคู่
 *
 * @param {"live"|"mixed"|"local"|"demo"} source
 * @param {boolean} [compact] แสดงเฉพาะไอคอน (ในตารางที่ที่แคบ) — ยังมี title ให้อ่านได้
 */
export default function DataSourceBadge({ source = "demo", compact = false }) {
  const t = useT();
  const KINDS = ["live", "mixed", "local", "demo"];
  const kind = KINDS.includes(source) ? source : "demo";

  const LABEL = {
    live: t("ข้อมูลจริง"),
    mixed: t("จริง + ตัวอย่าง"),
    local: t("บันทึกในเครื่องนี้"),
    demo: t("ข้อมูลตัวอย่าง"),
  };
  const TITLE = {
    live: t("ต่อกับเซนเซอร์จริงอยู่"),
    mixed: t("ตัวเลขนี้รวมฟาร์มที่ต่อเซนเซอร์จริงกับฟาร์มตัวอย่างไว้ด้วยกัน ยังเอาไปตัดสินใจทั้งก้อนไม่ได้"),
    local: t("เลขที่กรอกไว้ในเครื่องนี้ ยังไม่เข้าระบบกลาง เครื่องอื่นจะไม่เห็นตัวเลขนี้"),
    demo: t("ตัวเลขสมมติสำหรับลองใช้งาน ยังไม่ได้ต่อเซนเซอร์"),
  };
  const ICON = { live: "wifi", mixed: "monitor", local: "monitor", demo: "monitor" };

  return (
    <span className={`source-badge is-${kind}${compact ? " is-compact" : ""}`} title={TITLE[kind]}>
      <Icon name={ICON[kind]} size={15} />
      {compact ? null : LABEL[kind]}
    </span>
  );
}
