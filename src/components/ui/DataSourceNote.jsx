import Icon from "./Icon.jsx";
import { useT } from "../../lib/i18n/useT.js";
import "./ui.css";

/**
 * บรรทัดอธิบายที่มาของข้อมูลทั้งหน้า — วางไว้**ก่อน**ตัวเลข ไม่ใช่ท้ายหน้า
 *
 * ทำไมต้องมีทั้งที่มี `DataSourceBadge` อยู่แล้ว: ป้ายบอกได้ว่ากล่องไหนเป็นอะไร
 * แต่ไม่ได้บอกว่า "แล้วฉันควรทำยังไงกับตัวเลขนี้" คนที่เพิ่งเปิดหน้าครั้งแรกต้องรู้ก่อนอ่านตัวเลข
 * ว่าเชื่อได้แค่ไหน — เคยเป็นปัญหาจริง หน้าการเงินเป็นเลขสมมติทั้งหน้าโดยไม่มีอะไรบอกเลย (T1.283)
 *
 * ไม่ใช่กล่องเตือน (ไม่ได้มีอะไรพัง) จึงเป็นบรรทัดเบา ๆ ไม่ใช่การ์ดสีแดง
 * แต่ต้องอ่านออกจริง ไม่ใช่สีจาง ๆ ที่คนเลื่อนผ่าน
 *
 * @param {"demo"|"mixed"} source ทั้งหน้าเป็นข้อมูลตัวอย่าง หรือปนกันระหว่างของจริงกับตัวอย่าง
 * @param {string} [text] เขียนข้อความเองแทนค่าตั้งต้น (ต้องผ่าน t() มาแล้ว)
 */
export default function DataSourceNote({ source = "demo", text }) {
  const t = useT();
  const DEFAULT = {
    demo: t(
      "ทั้งหน้านี้เป็นข้อมูลตัวอย่างสำหรับสาธิตการใช้งาน ยังไม่ได้ต่อกับข้อมูลจริงของฟาร์ม ตัวเลขที่เห็นจึงยังเอาไปตัดสินใจไม่ได้",
    ),
    mixed: t(
      "ป้ายบนหัวกล่องบอกที่มาของตัวเลข — ตอนนี้มีฟาร์มที่ต่อเซนเซอร์จริงอยู่ฟาร์มเดียว กล่องที่ติดป้ายว่าข้อมูลตัวอย่างยังเอาไปตัดสินใจไม่ได้",
    ),
  };
  return (
    <p className="source-note">
      <Icon name="monitor" size={17} aria-hidden="true" />
      {text ?? DEFAULT[source] ?? DEFAULT.demo}
    </p>
  );
}
