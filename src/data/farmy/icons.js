export const severityFor = (tone) =>
  tone === "red"
    ? { tone: "critical", label: "ร้ายแรง" }
    : tone === "amber"
      ? { tone: "warning", label: "เฝ้าระวัง" }
      : { tone: "good", label: "ทั่วไป" };
