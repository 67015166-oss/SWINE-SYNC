/**
 * Mock data: คุณภาพอากาศในโรงเรือน (NH₃ · CO₂ · H₂S) + เกณฑ์ตัดสินสถานะ
 * ใช้ในหน้า "สภาพแวดล้อมโรงเรือน" (/dashboard/environment)
 *
 * ชุดข้อมูลหลายฟาร์ม (barnsByFarm.js) เก็บแค่แอมโมเนีย ไม่มี CO₂/H₂S — ไฟล์นี้เติมให้
 * โดยคำนวณต่อยอดจากค่าที่โรงเรือนนั้นวัดได้จริง ไม่ใช่สุ่มลอย ๆ ตัวเลขจึงสมเหตุสมผลกัน:
 *   - ชื้นกว่าเกณฑ์ = มูลและพื้นคอกแห้งช้า ก๊าซจึงสะสมมากกว่า
 *   - ร้อนกว่า = สุกรหอบมากขึ้น CO₂ สูงขึ้น
 *   - โรงเรือนที่มีแจ้งเตือนค้างอยู่จะแย่กว่าหลังที่ปกติเสมอ
 * ค่าแกว่งผูกกับรหัสโรงเรือน จึงคงที่ทุกครั้งที่เปิดหน้า
 *
 * เมื่อต่อ API จริง: แทนที่ gasesFor() ด้วยค่าจากเซนเซอร์จริง โดยคงรูปผลลัพธ์เดิมไว้
 *
 * หน่วย: NH₃/CO₂/H₂S = ppm · ลม = เมตร/วินาที
 */

const round1 = (n) => Number(n.toFixed(1));

const hash = (text) =>
  [...text].reduce((acc, ch) => (acc * 31 + ch.charCodeAt(0)) >>> 0, 11);

/** ค่าแกว่งคงที่ (−span/2 ถึง +span/2) — ข้อความเดิมได้ค่าเดิมเสมอ */
const jitter = (seed, span) => ((hash(seed) % 1000) / 1000 - 0.5) * span;

/**
 * ก๊าซและแสงในโรงเรือนหนึ่งหลัง
 * @param {object|null} barn โรงเรือนจาก barnsByFarm.js (ต้องมี id · tempC · humidity · status · nh3)
 * @returns {{nh3:number|null, co2:number|null, h2s:number|null, light:number|null}}
 *          ออฟไลน์/ไม่มีค่า = null ทั้งชุด
 */
export function gasesFor(barn) {
  if (!barn || barn.tempC == null || barn.humidity == null) {
    return { nh3: null, co2: null, h2s: null, light: null };
  }

  /* ═══ ฟาร์มที่ต่อเซนเซอร์จริง: ห้ามเดาค่าก๊าซเด็ดขาด ═══
     สูตรข้างล่างนี้มีไว้เติมให้ฟาร์มตัวอย่างเท่านั้น ถ้าปล่อยให้ฟาร์มจริงใช้ด้วย
     หน้าจอจะขึ้นตัวเลข NH₃/CO₂/H₂S ใต้ป้าย "LIVE" ทั้งที่ไม่มีเซนเซอร์ตัวไหนวัดค่านั้นเลย
     — คนอ่านแยกไม่ออกว่าอันไหนวัดจริง อันไหนคำนวณเอา

     สภาพจริงของฟาร์มกำแพงเพชร (ตรวจ 30 ส.ค. 2569)
       · NH₃ · CO₂ — Node-RED ส่ง `nh3_3` กับ `co2_3` มาจริง 1,371 จุดใน 30 วัน
                     **แต่เป็น 0 ทุกจุด** (ต่ำสุด 0 สูงสุด 0) = อุปกรณ์อ่านไม่ได้ ไม่ใช่ค่าที่วัดได้
                     ยังเป็นแบบนี้อยู่ตอนย้ายมาใช้ PlotNexus (ตรวจซ้ำ 3 ก.ย. 2569: 0.0 ทั้ง 121 จุด
                     ใน 24 ชม.) ตัวกรองย้ายไปอยู่ที่ `lib/sensorHealth.js` แล้ว
       · H₂S      — **ไม่มี field นี้ใน InfluxDB เลย** ไม่มีเซนเซอร์ ไม่มีตัวแปร ไม่เคยมีค่า

     คืน `null` = หน้าจอขึ้นขีดกลาง + ป้าย "ไม่มีสัญญาณ" ซึ่งเป็นความจริง
     วันที่อีกทีมต่อเซนเซอร์ก๊าซสำเร็จ ค่าจะไหลผ่าน `barn.nh3` / `barn.co2` มาเองโดยไม่ต้องแก้ที่นี่ */
  if (barn.dataSource === "live") {
    return { nh3: barn.nh3 ?? null, co2: barn.co2 ?? null, h2s: null, light: null };
  }

  const humidLoad = (barn.humidity - 70) / 10;
  const heatLoad = (barn.tempC - 27) / 3;
  const risk = barn.status === "warning" ? 1 : 0;

  return {
    /* แอมโมเนียมีในข้อมูลโรงเรือนอยู่แล้ว ใช้ค่าจริงก่อนเสมอ */
    nh3:
      barn.nh3 ??
      Math.max(2, Math.round(9 + humidLoad * 3 + risk * 4 + jitter(`${barn.id}nh3`, 3))),
    co2:
      Math.round(
        (760 + humidLoad * 90 + heatLoad * 70 + risk * 130 + jitter(`${barn.id}co2`, 120)) / 10
      ) * 10,
    h2s: round1(
      Math.max(0.2, 1.4 + humidLoad * 0.6 + risk * 0.9 + jitter(`${barn.id}h2s`, 0.6))
    ),
    /* ความสว่างในโรงเรือน (lux) — ไฟส่องสว่างคงที่ ไม่ได้ขึ้นกับอากาศข้างนอก */
    light: Math.round(180 + jitter(`${barn.id}lux`, 90)),
  };
}

/**
 * เกณฑ์ของค่าอากาศแต่ละตัว
 * max = ค่าสูงสุดที่ยังรับได้ · min = ต่ำกว่านี้ก็ไม่ดี (มีเฉพาะลม) · scaleMax = ปลายหลอดบนหน้าจอ
 */
export const AIR_LIMITS = {
  /* หน่วยของก๊าซทั้งสามตัวคือ ppm (ส่วนในล้านส่วน) — เป็นหน่วยมาตรฐานของงานคุณภาพอากาศ
     ในโรงเรือนปศุสัตว์ทั้งสามตัว ไม่ใช่ mg/m³ (ถ้าจะเปลี่ยนหน่วยต้องแปลงค่าด้วย ไม่ใช่แก้แค่ป้าย)

     ที่มาของเพดานแต่ละตัว
       · NH₃ 15 ppm  ค่าที่แนะนำสำหรับสุกรอยู่ราว 11 ppm ส่วน 25 ppm เป็นเพดานความปลอดภัย
                     ของคนทำงาน — ระบบเลือก 15 เป็นทางสายกลาง **และต้องตรงกับ `nh3Limit`
                     ใน settings/defaults.js กับตาราง alert_rule ที่หลังบ้าน** (ตอนนี้ตรงกันทั้งสามที่)
                     เดิมตรงนี้เป็น 25 ซึ่งหลวมกว่าที่หน้าจอเขียนไว้ ถ้าลืมส่ง maxOverride
                     ค่า 17 ppm จะขึ้นเขียวทั้งที่ป้ายข้าง ๆ เขียนว่า "ไม่เกิน 15"
       · CO₂ 2000 ppm  ตำราแนะนำให้เพิ่มการระบายอากาศเมื่อเกิน 3,000 ppm และถือว่าต่ำกว่า
                     2,000 ppm คือระบายมากเกินจำเป็น — ใช้ 2,000 เป็นเพดานฝั่งเข้มไว้ก่อน
       · H₂S 5 ppm   สภาพปกติที่มูลไม่ถูกกวนจะต่ำกว่า 1 ppm ส่วนผลต่อทางเดินหายใจเริ่มที่ 10 ppm
                     ใช้ 5 ppm เป็นเส้นเตือนก่อนถึงระดับที่เป็นอันตราย */
  nh3: { label: "แอมโมเนีย NH₃", unit: "ppm", max: 15, scaleMax: 40, icon: "wind" },
  co2: { label: "คาร์บอนไดออกไซด์ CO₂", unit: "ppm", max: 2000, scaleMax: 3000, icon: "cloud" },
  h2s: { label: "ไฮโดรเจนซัลไฟด์ H₂S", unit: "ppm", max: 5, scaleMax: 8, icon: "warn" },
  wind: { label: "ความเร็วลมภายใน", unit: "ม./วิ", min: 0.5, max: 3, scaleMax: 4, icon: "fan" },
};

/**
 * สถานะของค่าอากาศหนึ่งค่าเทียบเกณฑ์ — คืน tone/label แบบเดียวกับ readingStatus()
 * เกิน 1.4 เท่าของเพดานถือว่าวิกฤต (ไม่ใช่แค่เฝ้าระวัง)
 *
 * @param {"nh3"|"co2"|"h2s"|"wind"} kind
 * @param {number|null} value
 * @param {number} [maxOverride] เพดานที่ผู้ใช้ตั้งเองในหน้าตั้งค่า (ตอนนี้มีแค่แอมโมเนีย)
 *   **ต้องส่งมาทุกครั้งที่หน้าจอโชว์เกณฑ์ของผู้ใช้** ไม่งั้นป้ายสถานะจะตัดสินด้วยเลขคนละตัว
 *   กับเกณฑ์ที่เขียนอยู่ข้าง ๆ (เช่นโชว์ "ไม่เกิน 15 ppm" แต่ตัดสินที่ 25 → 17 ppm ขึ้นเขียว)
 * @param {boolean} [suspect] อุปกรณ์ยังส่งค่าอยู่แต่ค่าที่ส่งเชื่อไม่ได้ (ดู lib/sensorHealth.js)
 */
export function airStatus(kind, value, maxOverride, suspect = false) {
  /* ค่าถูกกรองทิ้งเพราะเชื่อไม่ได้ ≠ ไม่มีเซนเซอร์ตัวนั้น — ต้องแยกสองอย่างนี้ให้คนดูเห็น
     "ไม่มีสัญญาณ" (เทา) แปลว่าไม่มีอะไรมาให้ดู ส่วน "สงสัยเซนเซอร์" (เหลือง) แปลว่า
     มีอุปกรณ์อยู่และยังส่งค่าอยู่ แต่ค่าที่ส่งเป็นไปไม่ได้ = มีของต้องไปตามซ่อม
     (เช็กก่อน value == null เพราะค่าที่น่าสงสัยถูกกรองเป็น null ไปแล้วตั้งแต่ปากทาง) */
  if (suspect) return { tone: "warning", label: "สงสัยเซนเซอร์", suspect: true };
  if (value == null) return { tone: "offline", label: "ไม่มีสัญญาณ" };
  const base = AIR_LIMITS[kind];
  if (!base) return { tone: "good", label: "อยู่ในเกณฑ์" };
  const limit = maxOverride == null ? base : { ...base, max: maxOverride };

  if (value > limit.max * 1.4) return { tone: "critical", label: "สูงเกินมาก" };
  if (value > limit.max) return { tone: "warning", label: "สูงกว่าเกณฑ์" };
  if (limit.min != null && value < limit.min) {
    return { tone: "warning", label: "ลมน้อยเกินไป" };
  }
  return { tone: "good", label: "อยู่ในเกณฑ์" };
}
