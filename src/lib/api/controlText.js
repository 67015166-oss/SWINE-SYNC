/**
 * ข้อความสถานะของคำสั่งอุปกรณ์ (T1.310)
 *
 * ★ แยกออกมาจาก `control.js` เพราะไฟล์นั้น import `client.js` ซึ่งใช้ `import.meta.env`
 *   ทำให้เทสต์เรียกไม่ได้ — แบบเดียวกับที่ `summaryStats.js` ถูกแยกออกมา
 */
/**
 * ข้อความสั้นบอกว่าคำสั่งนี้ไปถึงไหนแล้ว — ใช้ทั้งแถบแจ้งผลและประวัติ
 *
 * ★ `held` มีสองความหมายที่ต่างกันมาก (T1.310) จึงต้องดู `transport` ด้วย
 *   `hold`   ไม่มีทางส่งเลย คำสั่งจะค้างอยู่อย่างนั้น
 *   `outbox` รออยู่ในกล่องขาออก Node-RED จะมารับไปส่งให้ตู้ควบคุมในไม่กี่วินาที
 *   ถ้าบอกเหมือนกันทั้งสองแบบ คนกดจะเข้าใจผิดว่าไม่มีอะไรเกิดขึ้น ทั้งที่กำลังจะเกิด
 */
export const statusText = (status, transport) => {
  if (status === "held" && transport === "outbox")
    return "เข้าคิวแล้ว กำลังรอส่งให้ตู้ควบคุม";
  return TEXT[status] ?? status;
};

const TEXT =
  ({
    held: "เข้าคิวแล้ว ยังไม่ถูกส่งออก (ยังไม่มีสิทธิ์เขียนเข้าระบบฟาร์ม)",
    sent: "ส่งออกไปแล้ว รอตู้ควบคุมยืนยัน",
    confirmed: "ตู้ควบคุมยืนยันแล้ว",
    failed: "ส่งไม่สำเร็จ",
    rejected: "ถูกปฏิเสธที่ด่านความปลอดภัย",
  });

/**
 * ฉบับสั้นของข้อความเดียวกัน — ใช้ในบรรทัดเล็กใต้ชื่ออุปกรณ์ (T1.336)
 *
 * ★ อยู่ไฟล์เดียวกับ `statusText` โดยเจตนา และมีเทสต์เทียบว่าสองชุดรู้จักสถานะชุดเดียวกัน
 *   ถ้าแยกไปไว้คนละที่ วันหนึ่งหลังบ้านเพิ่มสถานะใหม่แล้วชุดสั้นจะโชว์รหัสดิบเงียบ ๆ
 *
 * ★ `held` ยังต้องแยกตาม `transport` เหมือนฉบับเต็ม (เหตุผลเต็มอยู่ที่ `statusText`)
 *   — ย่อข้อความได้ แต่ห้ามย่อจนสองสถานการณ์ที่ต่างกันมากกลายเป็นคำเดียวกัน
 */
export const statusShort = (status, transport) => {
  if (status === "held") return transport === "outbox" ? "รอส่งให้ตู้" : "ค้างในคิว";
  return SHORT[status] ?? status;
};

const SHORT =
  ({
    held: "ค้างในคิว",
    sent: "ส่งแล้ว",
    confirmed: "ตู้ยืนยันแล้ว",
    failed: "ส่งไม่สำเร็จ",
    rejected: "ถูกปฏิเสธ",
  });
