/** ไกลสุดที่โมเดลชุดนี้ทำนาย (ชั่วโมง) — ใช้เมื่อภาพนิ่งไม่ได้บอกมาเอง */
export const DEFAULT_HORIZON_H = 24;

/** เก่าเกินกี่ชั่วโมงถึงเริ่มเตือน — สั้นกว่าช่วงทำนายหนึ่งช่วง จะได้เตือนก่อนหมดอายุจริง */
const WARN_AFTER_H = 6;

/**
 * ไกลสุดที่ภาพนิ่งใบนี้ทำนาย อ่านจากตัวมันเอง
 * @param {{horizons?: Array<{horizon_h?: number}>}|null} snapshot
 */
export function horizonOf(snapshot) {
  const hours = (snapshot?.horizons ?? [])
    .map((h) => Number(h?.horizon_h))
    .filter((n) => Number.isFinite(n) && n > 0);
  return hours.length ? Math.max(...hours) : DEFAULT_HORIZON_H;
}

/**
 * ตัดสินว่าภาพนิ่งใบนี้เก่าแค่ไหน — **ตัวตัดสินตัวเดียวของทั้งแอป**
 *
 * @param {number|null|undefined} ageMinutes อายุไฟล์เป็นนาที (หลังบ้านส่งมา)
 * @param {number} horizonH ไกลสุดที่ทำนาย (ชั่วโมง)
 * @returns {{level: "unknown"|"fresh"|"old"|"expired", hours: number|null, horizonH: number}}
 *   `expired` = เก่ากว่าช่วงที่ทำนายไว้ทั้งหมด — ตัวเลขบนจอพูดถึงเวลาที่ผ่านไปแล้ว
 *   `unknown` = หลังบ้านไม่ได้ส่งอายุมา ห้ามเดาว่าสด (เงียบไว้ดีกว่าโกหก)
 */
export function modelAge(ageMinutes, horizonH = DEFAULT_HORIZON_H) {
  /* ★ ต้องกัน null/undefined/"" ก่อน — `Number(null)` คือ **0** ซึ่งผ่าน `Number.isFinite`
     แล้วกลายเป็น "เพิ่งคำนวณเมื่อศูนย์นาทีที่แล้ว" ทั้งที่แปลว่า "ไม่รู้อายุ"
     (บั๊กชนิดเดียวกับ T1.341 — ค่าที่แปลว่า "ไม่รู้" ถูกกดให้กลายเป็น "ศูนย์") */
  if (ageMinutes == null || ageMinutes === "") return { level: "unknown", hours: null, horizonH };
  const n = Number(ageMinutes);
  if (!Number.isFinite(n) || n < 0) return { level: "unknown", hours: null, horizonH };
  const hours = n / 60;
  if (hours >= horizonH) return { level: "expired", hours, horizonH };
  if (hours >= WARN_AFTER_H) return { level: "old", hours, horizonH };
  return { level: "fresh", hours, horizonH };
}
