/**
 * อ่านข้อมูลเซนเซอร์จาก PlotNexus Lab — API ที่ทีมอื่นเปิดให้ (ผู้ใช้ได้กุญแจมา 2 ก.ย. 2569)
 *
 * ═══ ★ ปิดอยู่ตั้งแต่ 19 ต.ค. 2569 (T1.342) ═══
 * กุญแจถูกถอนสิทธิ์ตั้งแต่ 11 ก.ย. 2569 ทุกคำขอตอบ 403 — แอปจึงยิงไปโดนกำแพง
 * ทุกครั้งที่ยังไม่ได้เข้าสู่ระบบ **มาหกสัปดาห์** แล้วถอยไปใช้ข้อมูลตัวอย่างเงียบ ๆ
 * (เห็นเองในคอนโซลตอนตรวจงาน 16 ต.ค.) ข้อมูลจริงย้ายไปอยู่ที่กล่อง box-mew หมดแล้ว
 *
 * ไม่ลบไฟล์ทิ้ง เพราะถ้าพี่เลี้ยงคืนสิทธิ์ แค่ตั้ง `VITE_PLOTNEXUS_ENABLED=1` ก็กลับมาใช้ได้
 * (ตัวเก็บข้อมูลของคลังเทรนโมเดลใช้วิธีเดียวกัน — ดู `weather/collector/src/config.js`)
 *
 * เดิมเคยเป็นแหล่งข้อมูลจริงหลักของแอป แทนหลังบ้าน `server/` ที่รันในเครื่อง
 * ข้อดีตอนนั้นคือหน้าเว็บที่วางบนโฮสต์คนอื่นก็เห็นค่าจริงด้วย
 *
 * ═══ กุญแจตัวนี้ต่างจากกุญแจ AI ═══
 * กุญแจ AI **ห้าม**ขึ้นต้นด้วย `VITE_` เด็ดขาด เพราะจะถูกฝังลงไฟล์ที่ทุกคนโหลดได้
 * แต่กุญแจตัวนี้ **ตั้งใจให้อยู่ฝั่งหน้าเว็บ**:
 *   · เจ้าของบริการบอกเองว่าหน้าที่วางไว้ใครมีลิงก์ก็เปิดได้ และจะเห็นกุญแจในโค้ด
 *   · เป็นกุญแจ **อ่านอย่างเดียว** (ขึ้นต้น `labro_` = lab read-only) แก้ข้อมูลไม่ได้
 * ถ้าวันหนึ่งได้กุญแจที่เขียนข้อมูลได้มา **ห้ามเอามาใส่ที่นี่** ต้องผ่านหลังบ้านเท่านั้น
 *
 * รูปคำตอบเป็นคีย์ภาษาไทยทั้งหมด (`ค่า` `เส้น` `สรุป` …) — ไฟล์นี้เป็นที่เดียวที่รู้เรื่องนั้น
 * ข้างนอกได้รูปที่แปลงแล้วจาก plotnexusFarms.js
 */
const BASE = "https://lab.plotnexuslab.com/api";

const KEY = import.meta.env.VITE_PLOTNEXUS_KEY || "";

/** ★ ต้องเปิดด้วยมือเท่านั้น — เหตุผลอยู่หัวไฟล์ ค่าตั้งต้นคือปิด */
const ENABLED = import.meta.env.VITE_PLOTNEXUS_ENABLED === "1";

/** เรียกแหล่งนี้ได้ไหม — ต้อง**ทั้ง**เปิดไว้และมีกุญแจ */
export const plotnexusReady = ENABLED && Boolean(KEY);

/** ชุดข้อมูลของฟาร์มสุกรกำแพงเพชร (อีกสองชุดเป็นแปลงดิน/เสาอากาศที่แสลงพัน คนละที่กัน) */
export const PIG_SOURCE = "pig";

async function get(path, params, signal) {
  /* ★ กันไว้ที่ปากทางด้วย ไม่ใช่เช็กแค่ที่คนเรียก — ถ้าวันหนึ่งมีใครเพิ่มที่เรียกใหม่
     แล้วลืมเช็ก `plotnexusReady` จะได้ล้มทันทีตรงนี้ ไม่ใช่เงียบ ๆ ไปยิง 403 ต่อ */
  if (!ENABLED) throw new Error("แหล่งข้อมูล PlotNexus ถูกปิดไว้ (ตั้ง VITE_PLOTNEXUS_ENABLED=1 เพื่อเปิดคืน)");
  if (!KEY) throw new Error("ยังไม่ได้ตั้งกุญแจ VITE_PLOTNEXUS_KEY");
  const url = new URL(BASE + path);
  url.searchParams.set("key", KEY);
  for (const [k, v] of Object.entries(params ?? {})) {
    if (v !== undefined && v !== null && v !== "") url.searchParams.set(k, String(v));
  }
  const res = await fetch(url, { headers: { Accept: "application/json" }, signal });
  const data = await res.json().catch(() => null);
  /* บริการนี้ส่งคำอธิบายข้อผิดพลาดเป็นภาษาไทยมาให้อยู่แล้ว — ส่งต่อตรง ๆ ดีกว่าเขียนเอง */
  if (!res.ok || data?.error) {
    const err = new Error(data?.error || `เรียก ${path} ไม่สำเร็จ (HTTP ${res.status})`);
    /* แนบรหัสไว้ให้หน้าจอแยก "กุญแจถูกปฏิเสธ" (401/403) ออกจาก "ต่อไม่ติด"
       สองอาการนี้แก้คนละที่ — ถ้าบอกรวม ๆ ว่าต่อไม่ได้ คนจะไปไล่แก้ผิดจุด */
    err.status = res.status;
    throw err;
  }
  return data;
}

/** ค่าล่าสุดทุกตัวของชุดข้อมูล */
export const fetchLatest = (source = PIG_SOURCE, signal) => get("/latest", { source }, signal);

/** ข้อมูลตามเวลาไว้ทำกราฟ — คืนหลายเส้น เส้นละจุดติดตั้ง */
export const fetchSeries = (source, measure, hours, signal) =>
  get("/series", { source, measure, hours }, signal);

/**
 * ต่ำสุด/สูงสุด/เฉลี่ยของทุกค่าที่วัด ในช่วง `hours` ชั่วโมงที่ผ่านมา
 *
 * **ต้องใช้ตัวนี้หาค่าสูงสุด/ต่ำสุด ห้ามคำนวณเอาเองจาก `/series`** — `/series`
 * ส่งค่าที่**เฉลี่ยรายช่วงมาแล้ว** (24 ชม. ได้ 121 จุด = ช่วงละ ~12 นาที)
 * ยอดแหลมจริงถูกกลืนไปกับค่าเฉลี่ยของช่วงนั้น เอามาหา min/max จึงได้ช่วงที่แคบกว่าจริง
 * จนเคยขึ้นจอว่า "สูงสุด 27.7 °C" ทั้งที่ค่าปัจจุบันข้าง ๆ กันเขียน 28.4 °C (T1.225)
 *
 * คำตอบเป็นรายการแบน หนึ่งแถวต่อ (จุดติดตั้ง × ค่าที่วัด) — ผู้เรียกต้องกรองจุดที่ต้องการเอง
 */
export const fetchSummary = (source, hours, signal) =>
  get("/summary", { source, hours }, signal);

