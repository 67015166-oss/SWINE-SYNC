/**
 * "คำถามนี้แค่อยากรู้ค่าตอนนี้ใช่ไหม" — ถ้าใช่ ตอบเองได้ทันทีจากฐานข้อมูลเรา
 *
 * **ทำไมถึงคุ้มที่จะแยกออกมา** วัดแล้ว AI ใช้เวลา **28–150 วินาที** กับคำถามแค่
 * "ตอนนี้กี่องศา" เพราะทุกคำถามเรื่องเซนเซอร์ถูกส่งเข้าโมเดลหมดและต้องเข้าคิว
 * ขณะที่ค่าชุดเดียวกันอยู่ในฐานข้อมูลเราเองอยู่แล้ว อ่านได้ใน **0.1 วินาที**
 *
 * **แต่ห้ามฉกทุกคำถามที่มีคำว่าอุณหภูมิ** — "อุณหภูมิเท่าไรถึงจะอันตรายกับหมู"
 * เป็นคำถามความรู้ ไม่ใช่ขอค่า ตอบด้วยเลข 26.7 °C ไปก็ไม่ตรงคำถาม
 * ➜ ต้องเข้าเงื่อนไขครบสามข้อถึงจะนับ ตกข้อไหนก็ส่งให้ AI ตามเดิม
 */

import { matchesAny, matchesAnyExact } from "../text/match.js";

/** คำที่บอกว่าถามถึงค่าอะไร */
const METRICS = [
  [["อุณหภูมิ", "องศา", "ร้อน", "เย็น", "หนาว"], "temp_c"],
  [["ความชื้น", "ชื้น"], "humidity"],
  [["ลม", "การไหลอากาศ", "ระบายอากาศ"], "wind_ms"],
  [["แอมโมเนีย", "nh3"], "nh3"],
  [["co2", "คาร์บอน"], "co2"],
];

/** ไม่ระบุค่าไหน แต่ถามถึงสภาพรวม — ตอบให้หมดทุกค่า */
const ALL_WORDS = ["อากาศ", "สภาพแวดล้อม", "ค่าเซนเซอร์", "เซนเซอร์", "environment"];

/** คำที่บอกว่า "ขอตัวเลข" ไม่ใช่ "ขอความเห็น" */
const WANTS_VALUE = [
  "เท่าไร", "เท่าไหร่", "กี่", "ตอนนี้", "ล่าสุด", "ปัจจุบัน", "เป็นยังไง",
  "เป็นไง", "สถานะ", "ค่า", "ขณะนี้",
  /* คำขอแบบพูด — "ช่วยบอกอุณหภูมิหน่อย" คือขอค่า ไม่ต่างจาก "อุณหภูมิเท่าไหร่"
     แต่เดิมตกข้อนี้เพราะประโยคยาวเกิน 14 ตัวอักษรและไม่มีคำว่า "เท่าไหร่"
     แล้วไปได้คำตอบเรื่องหลังที่ร้อนที่สุดแทน (ผู้ใช้แจ้ง 17 ก.ย. 2569)
     คนพูดใส่ไมค์ใช้รูปนี้บ่อยกว่าคนพิมพ์มาก */
  "บอก", "หน่อย", "เช็ก",
];

/**
 * คำที่บอกว่าอยากได้ "ความเห็น/คำอธิบาย" ไม่ใช่ตัวเลข — ตรงนี้ AI เก่งกว่าเรามาก
 * เจอคำพวกนี้ให้ปล่อยผ่านไปหา AI ทันที ถึงจะช้ากว่าก็ตอบได้ตรงกว่า
 */
const WANTS_THINKING = [
  "ควร", "แนะนำ", "ทำไม", "เพราะ", "วิเคราะห์", "สรุป", "เหมาะ", "อันตราย",
  "เสี่ยง", "ผลกระทบ", "ป้องกัน", "แก้ไข", "รับมือ", "เทียบ", "เปรียบเทียบ",
  "แนวโน้ม", "ย้อนหลัง", "พยากรณ์", "โรค", "ป่วย", "ตาย", "ราคา", "อาหาร",
  /* ── ช่วงเวลาข้างหน้า (เพิ่ม 24 ก.ย. 2569 · T1.282) ──
     มีแต่คำว่า "พยากรณ์" ไม่พอ — ทดสอบแล้ว "อากาศพรุ่งนี้เป็นยังไง" หลุดตัวกันนี้มา
     แล้วถูกตอบด้วย**ค่าเซนเซอร์ตอนนี้** ซึ่งไม่ใช่คำตอบของคำถามนั้นเลย
     ค่าที่วัดได้ตอบได้แค่ "ตอนนี้" เท่านั้น อนาคตต้องให้ตัวที่มีแบบจำลองตอบ */
  "พรุ่งนี้", "มะรืน", "คืนนี้", "สัปดาห์หน้า", "เดือนหน้า", "ข้างหน้า",
];

/**
 * @param {string} question คำถามที่ผู้ใช้พิมพ์
 * @returns {string[]|null} รายชื่อค่าที่ถาม (ว่าง = เอาทุกค่า) หรือ null ถ้าไม่ใช่คำถามขอค่า
 */
export function currentReadingAsk(question) {
  const text = String(question ?? "").toLowerCase();
  if (!text.trim()) return null;

  /* 1. อยากได้ความเห็น ไม่ใช่ตัวเลข → ไม่ใช่งานของเรา
        **ตัวกัน จึงไม่เผื่อพิมพ์ผิด** — ติดเกินไปแปลว่าคำถามขอค่าธรรมดาจะถูกส่งไปรอ AI
        นานเป็นนาทีทั้งที่อ่านจากฐานข้อมูลเราได้ใน 0.1 วินาที */
  if (matchesAnyExact(question, WANTS_THINKING)) return null;

  /* 2. ต้องมีคำที่บอกว่าถามถึงค่าอะไร — ตรงนี้เผื่อพิมพ์ผิดและคำอังกฤษได้เต็มที่
        ("temp" "sensor" "อุนหภูมิ" ต้องรู้เรื่องหมด) */
  const asked = METRICS.filter(([words]) => matchesAny(question, words)).map(([, m]) => m);
  const broad = matchesAny(question, ALL_WORDS);
  if (asked.length === 0 && !broad) return null;

  /* 3. ต้องมีคำที่บอกว่า "ขอตัวเลข" — ไม่มีก็ยอมให้ผ่านได้ถ้าพิมพ์สั้นมาก
        ("อุณหภูมิ" คำเดียวคือขอค่าแน่ ๆ ส่วนประโยคยาว ๆ ที่ไม่มีคำขอค่าเลย มักเป็นอย่างอื่น) */
  if (!matchesAny(question, WANTS_VALUE) && text.length > 14) return null;

  return asked;
}
