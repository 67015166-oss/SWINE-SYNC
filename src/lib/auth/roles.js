/**
 * แปลงรหัสระดับที่เก็บไว้ → ระดับที่มีจริง
 * `user` คือค่ารุ่นก่อน T1.251 ที่อาจค้างใน localStorage (บัญชีที่จดจำไว้ · บันทึกเข้าใช้งาน)
 * — หลังบ้านย้ายเป็น editor แล้ว ฝั่งนี้จึงแปลงตาม
 * ค่าที่ไม่รู้จักตกไปที่ **ผู้ชม** (ต่ำสุด) — ค่าเพี้ยนต้องไม่กลายเป็นสิทธิ์สูง
 */
export const getAccountRole = (id) => {
  const key = id === "user" ? "editor" : id;
  return ACCOUNT_ROLES.find((r) => r.id === key) ?? ACCOUNT_ROLES[0];
};

/** ระดับนี้อยู่ขั้นเดียวกับหรือสูงกว่า `min` ไหม */
export const roleAtLeast = (roleId, min) =>
  ROLE_ORDER.indexOf(getAccountRole(roleId).id) >= ROLE_ORDER.indexOf(min);

/** สิทธิ์นี้ทำสิ่งนี้ได้ไหม — คีย์ที่ไม่มีในตารางคืน false เสมอ */
export const roleCan = (roleId, action) =>
  action in PERMISSIONS && roleAtLeast(roleId, PERMISSIONS[action]);

/** ระดับต่ำสุดที่ทำสิ่งนี้ได้ — ใช้เขียนเหตุผลว่า "ต้องมีสิทธิ์ระดับ … ขึ้นไป" */
export const minRoleFor = (action) => getAccountRole(PERMISSIONS[action] ?? "admin");
