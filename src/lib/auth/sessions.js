/**
 * บันทึกการเข้าใช้งาน + บัญชีที่ "จดจำไว้ในเครื่องนี้"
 *
 * สองเรื่องอยู่ไฟล์เดียวกันเพราะเป็นของคู่กัน — ทั้งคู่เป็นข้อมูลของ **เครื่องนี้เครื่องเดียว**
 * ไม่ใช่ของบัญชี ย้ายเครื่องแล้วเริ่มใหม่หมด (ตัวตนจริงอยู่ที่เซิร์ฟเวอร์ — ดู lib/auth/authApi.js)
 *
 * 1. **บัญชีที่จดจำไว้** (`swine-sync:remembered`) — รายชื่อคนที่เคยเข้าจากเครื่องนี้
 *    และตอบว่า "จดจำไว้" กดจากรายการแล้ว **เข้าระบบได้ทันทีในคลิกเดียว**
 *    `asked: false` = เคยตอบว่า "ไม่ต้องจดจำ" เก็บไว้เพื่อ **ไม่ถามซ้ำ** ไม่ใช่เพื่อจดจำ
 *
 *    **ไม่เก็บรหัสผ่านแล้ว** (เลิกตั้งแต่ทำ auth จริง 1 ก.ย. 2569) — ของเดิมเก็บแบบอ่านออกได้
 *    ตรง ๆ เพื่อให้กดทีเดียวเข้าเลย ใครเปิด devtools ในเครื่องนั้นก็อ่านได้ทั้งหมด
 *    ตอนนี้ไม่ต้องเก็บอีกแล้วเพราะ **session token อยู่ได้ 30 วัน** — เปิดแอปมาก็ยังล็อกอินค้างอยู่
 *    ไม่ต้องกรอกซ้ำ ซึ่งสะดวกกว่าเดิมด้วยซ้ำ และ token ถอนได้จากฝั่งเซิร์ฟเวอร์ (รหัสผ่านถอนไม่ได้)
 *    รายการนี้จึงเหลือหน้าที่เดียว: เติมชื่อผู้ใช้ให้ตอนพิมพ์ ไม่ได้เข้าระบบแทนคน
 *
 * 2. **ป้ายของบันทึกการเข้าใช้งาน** (`LOG_EVENTS`) — ตัวบันทึกย้ายไปอ่านจากเซิร์ฟเวอร์แล้ว (T1.255)
 *    เดิมจดไว้ใน localStorage (`swine-sync:auth-log`) จึงเห็นแค่การเข้าจากเบราว์เซอร์นั้น
 *    เวลาเลยไม่ตรงกับช่อง "เข้าล่าสุด" ของหน้าจัดการผู้ใช้ที่นับจากทุกเครื่อง
 *    ของเดิมที่ค้างในเครื่องลบทิ้งด้วย `dropLocalLog()`
 *
 * ทุกฟังก์ชันกันพังไว้หมด (localStorage อ่านไม่ได้ในโหมดส่วนตัวของบางเบราว์เซอร์
 * และค่าที่อ่านมาอาจถูกแก้มาแล้ว) — อ่านไม่ได้ให้ถือว่า "ยังไม่มีอะไร" ไม่ใช่ทำหน้าพัง
 */

const REMEMBER_KEY = "swine-sync:remembered";
/** ที่เก็บบันทึกรุ่นก่อน T1.255 — เหลือไว้แค่ให้ลบทิ้ง */
const OLD_LOG_KEY = "swine-sync:auth-log";

/**
 * จำนวนบัญชีที่จดจำได้สูงสุด — เกินนี้ตัวที่เก่าที่สุดหลุดออก
 * วัดจากของจริง: การ์ดล็อกอินกว้าง 460px ใส่ได้ 2 เม็ดต่อบรรทัด 3 บัญชีจึงเป็น 2 บรรทัด
 * ถ้าเพิ่มเป็น 4 จะกลายเป็น 3 บรรทัดและดันการ์ดยาวเกินจอ 900px ต้องเลื่อนถึงจะเห็นปุ่มเข้าสู่ระบบ
 */
export const REMEMBER_LIMIT = 3;

/**
 * ชนิดเหตุการณ์ที่บันทึก — ป้ายสถานะกับไอคอนผูกไว้ที่นี่ที่เดียว
 * ข้อความเป็นภาษาไทย (คีย์ของระบบแปล) หน้าจอเรียก t() ทับอีกที
 */
export const LOG_EVENTS = {
  signin: { label: "เข้าสู่ระบบ", tone: "good", icon: "login" },
  failed: { label: "รหัสผ่านไม่ถูกต้อง", tone: "critical", icon: "warn" },
  signout: { label: "ออกจากระบบ", tone: "offline", icon: "power" },
};

const read = (key, fallback) => {
  try {
    const raw = JSON.parse(localStorage.getItem(key) ?? "null");
    return Array.isArray(raw) ? raw : fallback;
  } catch {
    return fallback;
  }
};

const write = (key, value) => {
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch {
    /* เขียนไม่ได้ก็ยังใช้งานต่อได้ แค่จำข้ามการรีเฟรชไม่ได้ */
  }
};

/* ---------- บัญชีที่จดจำไว้ ---------- */

/** อ่านรายการบัญชีที่จดจำไว้ (ใหม่สุดขึ้นก่อน) — ตัดของที่โครงสร้างเพี้ยนทิ้ง */
/**
 * บัญชีที่จดจำไว้ในเครื่องนี้
 *
 * **ลบ `password` ที่ค้างอยู่จากรุ่นก่อนทิ้งทุกครั้งที่อ่าน** — เครื่องที่เคยใช้รุ่นเก่า
 * มีรหัสผ่านแบบอ่านออกได้นอนอยู่ใน localStorage การอัปเดตโค้ดอย่างเดียวไม่ได้ลบของเดิมให้
 * (ล้างตอน "อ่าน" ไม่ใช่ตอน "เขียน" เพราะบางบัญชีอาจไม่ถูกเขียนซ้ำอีกเลย) */
export const readRemembered = () =>
  read(REMEMBER_KEY, [])
    .filter((a) => a && typeof a.userId === "string" && a.userId !== "")
    .map(({ password: _drop, ...rest }) => rest);

/** เฉพาะบัญชีที่ตอบว่า "จดจำไว้" จริง ๆ — ใช้แสดงเป็นปุ่มลัดบนหน้าเข้าสู่ระบบ */
export const rememberedAccounts = () =>
  readRemembered().filter((a) => a.asked !== false);

/** เคยถามบัญชีนี้ไปแล้วหรือยัง (จดจำไว้ หรือ ตอบว่าไม่ต้อง ก็นับว่าถามแล้ว) */
export const wasAsked = (userId) =>
  readRemembered().some((a) => a.userId === userId);

/**
 * จดจำบัญชีนี้ไว้ — ย้ายขึ้นบนสุดเสมอ (คนที่เพิ่งเข้าอยู่ใกล้มือที่สุด)
 *
 * @param {boolean} asked false = ตอบว่า "ไม่ต้องจดจำ" (เก็บไว้กันถามซ้ำเท่านั้น)
 *
 * **ไม่รับรหัสผ่านแล้ว** — พารามิเตอร์ตัวที่สี่ถูกถอดออกตอนทำ auth จริง (1 ก.ย. 2569)
 * ถ้าเจอ `password` ค้างอยู่ในของที่เก็บไว้เดิม `readRemembered()` จะลบทิ้งให้เอง
 */
export function rememberAccount(userId, roleId, asked = true) {
  if (!userId) return readRemembered();
  const rest = readRemembered().filter((a) => a.userId !== userId);
  const head = { userId, roleId, asked, at: new Date().toISOString() };
  const all = [head, ...rest];
  /* จำกัดโควตาแยกกันสองชุด — ของที่ตอบว่า "ไม่ต้อง" ไม่ได้แสดงที่ไหนและมีไว้กันถามซ้ำเท่านั้น
     จึงไม่ควรไปเบียดบัญชีที่จดจำไว้จริงให้ตกรายการ */
  const saved = all.filter((a) => a.asked !== false).slice(0, REMEMBER_LIMIT);
  const declined = all.filter((a) => a.asked === false).slice(0, REMEMBER_LIMIT * 2);
  const next = all.filter((a) => saved.includes(a) || declined.includes(a));
  write(REMEMBER_KEY, next);
  return next;
}

/** ลืมบัญชีนี้ทิ้ง — ลบออกทั้งแถว ครั้งหน้าเข้ามาจึงถามใหม่ได้ */
export function forgetAccount(userId) {
  const next = readRemembered().filter((a) => a.userId !== userId);
  write(REMEMBER_KEY, next);
  return next;
}

/* ---------- บันทึกการเข้าใช้งานรุ่นเก่า ---------- */

/** ลบบันทึกที่เคยจดไว้ในเครื่อง — ไม่มีใครอ่านแล้ว และเวลาในนั้นไม่ตรงกับของเซิร์ฟเวอร์ */
export function dropLocalLog() {
  try {
    localStorage.removeItem(OLD_LOG_KEY);
  } catch {
    /* ลบไม่ได้ก็ไม่เป็นไร ไม่มีใครอ่านแล้ว */
  }
}
