/**
 * กติกาเรื่องพิกัดที่ทุกที่ต้องใช้ร่วมกัน
 *
 * แยกไว้ไฟล์เดียวเพราะเคยพลาดมาแล้ว: หน้าแผนที่เช็กแค่ `lat != null`
 * ฟาร์มที่พิกัดเป็นค่าว่าง ("") หรือ NaN จึงหลุดเข้าไปเป็นหมุด แล้วถูกคำนวณเป็นลองจิจูด 0
 * (กลางอ่าวกินี นอกชายฝั่งแอฟริกา) — แผนที่เลยต้องซูมออกจนเห็นทั้งแอฟริกาถึงอินเดีย
 * เพื่อครอบหมุดผีนั้นกับฟาร์มไทยพร้อมกัน
 */

/** ฟาร์มนี้มีพิกัดที่ใช้วาดหมุดได้จริงหรือไม่ (ต้องเป็นตัวเลขจริง และอยู่ในช่วงที่มีอยู่บนโลก) */
export function hasPin(farm) {
  const lat = Number(farm?.lat);
  const lng = Number(farm?.lng);
  return (
    farm?.lat !== null &&
    farm?.lat !== undefined &&
    farm?.lat !== "" &&
    farm?.lng !== null &&
    farm?.lng !== undefined &&
    farm?.lng !== "" &&
    Number.isFinite(lat) &&
    Number.isFinite(lng) &&
    lat >= -90 &&
    lat <= 90 &&
    lng >= -180 &&
    lng <= 180 &&
    /* (0, 0) อยู่กลางอ่าวกินี ไม่มีฟาร์มจริงตรงนั้นแน่ ๆ — เป็นค่าที่หลุดมาจากข้อมูลว่างเสมอ
       ถ้าปล่อยผ่าน แผนที่จะถูกลากไปครอบทั้งแอฟริกาเพื่อให้เห็นหมุดผีนี้พร้อมฟาร์มไทย */
    !(lat === 0 && lng === 0)
  );
}

