/** ขนาดตั้งต้นของกล่องที่ไม่เคยอยู่ในเลย์เอาต์มาก่อน */
export const FALLBACK_SIZE = { w: 3, h: 9 };

const clampInt = (n, min, max) =>
  Math.min(max, Math.max(min, Math.round(Number(n) || 0)));

/** ดัดค่าหนึ่งกล่องให้อยู่ในกริดเสมอ — กันค่าที่แก้มือมาจาก localStorage ทำหน้าพัง */
export const clampBlock = (block) => {
  const w = clampInt(block?.w ?? FALLBACK_SIZE.w, MIN_W, COLS);
  const h = clampInt(block?.h ?? FALLBACK_SIZE.h, MIN_H, MAX_ROWS);
  return {
    w,
    h,
    x: clampInt(block?.x ?? 0, 0, COLS - w),
    y: clampInt(block?.y ?? 0, 0, MAX_ROWS - h),
  };
};

/** สองกล่องนี้ทับกันไหม */
export const overlaps = (a, b) =>
  a.x < b.x + b.w && b.x < a.x + a.w && a.y < b.y + b.h && b.y < a.y + a.h;

/**
 * หาที่ว่างให้กล่องหนึ่งโดยไถลงล่างทีละแถวจนไม่ชนใคร
 * ใช้ตอนวางกล่องใหม่และตอนปล่อยเมาส์แล้วดันไปทับของเดิม —
 * เลือก "ดันลงล่าง" เพราะเป็นทิศเดียวที่ไม่มีวันตัน (กริดสูงได้เรื่อย ๆ)
 */
export function placeFree(block, others) {
  let placed = clampBlock(block);
  let guard = 0;
  while (others.some((other) => overlaps(placed, other)) && guard < MAX_ROWS) {
    placed = clampBlock({ ...placed, y: placed.y + 1 });
    guard += 1;
  }
  return placed;
}

/**
 * วางกล่องที่ผู้ใช้เพิ่งลากไว้ "ตรงที่ปล่อยจริง ๆ" แล้วดันใบที่ทับลงล่างแทน
 *
 * เคยลองวิธีตรงข้าม (ดันใบที่ลากลงไปหาที่ว่าง) แล้วใช้ไม่ได้เลย —
 * ลากไปทับใบข้าง ๆ ทีเดียวกล่องจะถูกไถลงไปใต้แผนที่สูง 16 แถวทันที
 * ผู้ใช้ต้องได้ตำแหน่งที่ตัวเองปล่อยเสมอ ส่วนใบอื่นค่อยหลบให้
 */
export function resolveCollisions(layout, movedId, moved) {
  const placed = clampBlock(moved);
  const settled = [placed];
  const next = { [movedId]: placed };

  /* ไล่ใบที่เหลือจากบนลงล่าง ใบที่อยู่สูงกว่าจึงได้สิทธิ์เลือกที่ก่อน */
  Object.keys(layout)
    .filter((id) => id !== movedId)
    .sort((a, b) => layout[a].y - layout[b].y || layout[a].x - layout[b].x)
    .forEach((id) => {
      let block = clampBlock(layout[id]);
      let guard = 0;
      while (settled.some((other) => overlaps(block, other)) && guard < MAX_ROWS) {
        block = clampBlock({ ...block, y: block.y + 1 });
        guard += 1;
      }
      next[id] = block;
      settled.push(block);
    });

  return next;
}

/**
 * จัดกล่องใหม่หลังผู้ใช้ลากไปวาง — พฤติกรรมแบบวิดเจ็ตบนไอโฟน
 *
 *   ลากใบ 1 ไปทับใบ 2 → ใบ 2 เด้งไปอยู่ที่เดิมของใบ 1 (สลับที่กัน)
 *   ถ้าสลับไม่ได้ (ทับหลายใบพร้อมกัน หรือที่เดิมมีคนอื่นแทรกอยู่แล้ว) → ดันลงบรรทัดใหม่
 *
 * @param {object} layout  เลย์เอาต์ก่อนหน้า
 * @param {string} movedId กล่องที่กำลังลาก
 * @param {object} target  ตำแหน่งใหม่ที่ผู้ใช้เล็งไว้
 * @param {object} origin  ตำแหน่งของกล่องนั้นตอนเริ่มลาก (ที่ว่างที่จะยกให้ใบที่ถูกทับ)
 */
export function arrange(layout, movedId, target, origin) {
  const moved = clampBlock(target);
  const others = Object.entries(layout).filter(([id]) => id !== movedId);

  /* พื้นที่ที่ทับกันของสองกล่อง — ใช้เลือกว่า "ตั้งใจจะวางทับใบไหน" */
  const overlapArea = (a, b) =>
    Math.max(0, Math.min(a.x + a.w, b.x + b.w) - Math.max(a.x, b.x)) *
    Math.max(0, Math.min(a.y + a.h, b.y + b.h) - Math.max(a.y, b.y));

  const hits = others
    .map(([id, block]) => [id, block, overlapArea(moved, block)])
    .filter(([, , area]) => area > 0)
    .sort((a, b) => b[2] - a[2]);

  if (hits.length > 0 && origin) {
    const [hitId, hitBlock, area] = hits[0];
    /* ต้องทับมากพอถึงจะนับว่า "ตั้งใจวางทับใบนี้" — เฉี่ยวมุมนิดเดียวไม่สลับ */
    const enough =
      area >= Math.min(moved.w * moved.h, hitBlock.w * hitBlock.h) * 0.25;

    /* ขนาดเท่ากัน = สลับรอยเท้ากันตรง ๆ ใบที่ลาก "ดูดเข้าช่อง" ของใบที่ถูกทับพอดี
       เป็นเคสที่เจอบ่อยที่สุด (กล่อง KPI ขนาดเท่ากันหมด) และเป็นพฤติกรรมของวิดเจ็ตบนไอโฟนเป๊ะ
       ➜ เคยให้ใบที่ลากอยู่ตรงที่ปล่อยดิบ ๆ ซึ่งพอวางคร่อมครึ่งใบแล้วสลับไม่ได้สักที
          เพราะรอยเท้าใหม่ไปทับที่เดิมของตัวเองที่เพิ่งยกให้อีกฝ่าย */
    if (enough && moved.w === hitBlock.w && moved.h === hitBlock.h) {
      return {
        ...layout,
        [movedId]: clampBlock({ ...moved, x: hitBlock.x, y: hitBlock.y }),
        [hitId]: clampBlock({ ...hitBlock, x: origin.x, y: origin.y }),
      };
    }

    /* ขนาดไม่เท่ากัน — ให้ใบที่ลากอยู่ตรงที่ปล่อย แล้วยกที่เดิมให้ใบที่ถูกทับ ถ้าลงตัว */
    const swapped = clampBlock({ ...hitBlock, x: origin.x, y: origin.y });
    const rest = others.filter(([id]) => id !== hitId).map(([, block]) => block);
    const fits =
      enough && !overlaps(swapped, moved) && !rest.some((block) => overlaps(swapped, block));
    if (fits) return { ...layout, [movedId]: moved, [hitId]: swapped };
  }

  return resolveCollisions(layout, movedId, moved);
}

