/**
 * ค่านี้อยู่ในเกณฑ์ปกติของอากาศข้างนอกไหม
 * @returns {{tone: "good"|"warning"|"offline", label: string}} รูปเดียวกับที่ StatusBadge รับ
 */
export function outdoorStatus(kind, value) {
  if (value == null) return { tone: "offline", label: "ไม่มีสัญญาณ" };
  const band = OUTDOOR_BANDS[kind];
  if (!band) return { tone: "good", label: "ปกติ" };
  if (value > band.max || (band.min != null && value < band.min)) {
    return { tone: "warning", label: "เฝ้าระวัง" };
  }
  return { tone: "good", label: "ปกติ" };
}

/** สัดส่วนของค่าบนหลอด (0–100) — ต่ำกว่าขอบล่างหรือเกินขอบบนถูกตัดให้อยู่ในหลอดเสมอ */
export const barPct = (value, floor, ceil) =>
  value == null ? 0 : Math.min(100, Math.max(0, ((value - floor) / (ceil - floor)) * 100));

/** หลอดของค่าภายนอกเริ่มจาก scaleMin ถ้ามี (ความกดอากาศแกว่งแคบ เริ่มจาก 0 แล้วดูไม่ออก) */
export function outdoorPct(kind, value) {
  const band = OUTDOOR_BANDS[kind];
  if (!band) return 0;
  return barPct(value, band.scaleMin ?? 0, band.scaleMax);
}

/**
 * องศาทิศลม → ชื่อทิศภาษาไทย
 *
 * เสาอากาศส่งมาเป็นองศา (0–360) ซึ่งอ่านแล้วนึกภาพไม่ออกว่าลมมาจากไหน
 * แปลงเป็น 8 ทิศพอ — 16 ทิศละเอียดเกินกว่าที่คนดูแลฟาร์มจะใช้ตัดสินใจอะไรได้
 * (ลมตะวันตกเฉียงใต้กับตะวันตกเฉียงใต้ค่อนตะวันตก ไม่ได้ทำให้ทำอะไรต่างกัน)
 */
const COMPASS = [
  "เหนือ",
  "ตะวันออกเฉียงเหนือ",
  "ตะวันออก",
  "ตะวันออกเฉียงใต้",
  "ใต้",
  "ตะวันตกเฉียงใต้",
  "ตะวันตก",
  "ตะวันตกเฉียงเหนือ",
];

/** @returns {string|null} null = ไม่มีค่า (ให้หน้าจอขึ้นขีดกลางเอง) */
export function windDirectionName(deg) {
  if (deg == null || Number.isNaN(Number(deg))) return null;
  /* บวกครึ่งช่อง (22.5°) ก่อนหาร เพื่อให้ 350° ปัดเป็น "เหนือ" ไม่ใช่ "ตะวันตกเฉียงเหนือ" */
  const index = Math.round(((Number(deg) % 360) + 360) % 360 / 45) % 8;
  return COMPASS[index];
}
