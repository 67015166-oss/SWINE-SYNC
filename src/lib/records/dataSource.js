/**
 * รวม "ที่มาของข้อมูล" หลายชิ้นให้เป็นป้ายเดียว
 *
 * ทำไมต้องมีสถานะที่สาม: กล่องสรุปในหน้าภาพรวมเป็นตัวเลข**รวมทุกฟาร์ม** ซึ่งตอนนี้
 * มีฟาร์มที่ต่อเซนเซอร์จริงอยู่ฟาร์มเดียว ที่เหลือเป็นข้อมูลตัวอย่าง
 * ป้าย "ข้อมูลจริง" จึงเกินความจริง และ "ข้อมูลตัวอย่าง" ก็ไม่ตรงเหมือนกัน
 *
 * **ตั้งใจให้ตอบตามของที่มีจริงตอนนั้น ไม่ใช่เขียนตายตัว** — ผู้ใช้ลบฟาร์มตัวอย่างออกหมด
 * ป้ายต้องเปลี่ยนเป็น "ข้อมูลจริง" เอง และวันที่ต่อเซนเซอร์ฟาร์มที่สองก็ไม่ต้องมาแก้โค้ดตรงนี้
 *
 * @param {boolean} hasReal   ตัวเลขนี้มีส่วนที่มาจากเซนเซอร์จริงไหม
 * @param {boolean} hasSample ตัวเลขนี้มีส่วนที่เป็นข้อมูลตัวอย่างไหม
 * @returns {"live"|"mixed"|"demo"}
 */
export const blendSource = (hasReal, hasSample) =>
  hasReal && hasSample ? "mixed" : hasReal ? "live" : "demo";
