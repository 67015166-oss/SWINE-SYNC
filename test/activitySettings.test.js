/**
 * ช่องติ๊ก "ส่งกิจกรรมของคนเข้าไลน์" (T1.367)
 *
 * ═══ ★★ บั๊กที่เทสต์ชุดนี้มีไว้กัน ═══
 * ของเดิมอ่านค่าที่ตั้งไว้ใน `setState((p) => …)` ออกมาใช้ต่อทันที
 *   let next = null;
 *   setState((p) => { next = …; return …; });
 *   apiPut(path, { lineKinds: next });     // ← next ยังเป็น null
 *
 * **React ไม่ได้เรียกฟังก์ชันนั้นทันที** ค่าที่ส่งไปจึงเป็น `null` ทุกครั้ง
 * เซิร์ฟเวอร์ตอบ 400 แล้วช่องเด้งกลับ — ติ๊กไม่ติดสักครั้ง (ผู้ใช้แจ้งเอง)
 *
 * ★ เป็นบั๊กที่ **เทสต์ปกติจับไม่ได้** เพราะต้องมีตัววาด React ถึงจะเห็น
 *   จึงกันด้วยการอ่านซอร์สแทน — แบบเดียวกับที่ `barnLog.test.js` อ่าน migration
 */
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const src = readFileSync(new URL("../src/lib/api/activity.js", import.meta.url), "utf8");
/* ★ ตัดคอมเมนต์ออกก่อนตรวจ — ในไฟล์มีคอมเมนต์อธิบายรูปที่เคยพังไว้เป็นตัวอย่าง
   ถ้าไม่ตัด เทสต์จะไปจับคำอธิบายของตัวเองแล้วฟ้องผิด (เจอตอนเขียนเทสต์นี้เอง) */
const code = src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");

test("★★ ห้ามอ่านค่าที่ตั้งในฟังก์ชันของ setState ออกมาใช้ต่อ", () => {
  /* รูปที่เคยพัง: ประกาศตัวแปรไว้ข้างนอก แล้วไปกำหนดค่าข้างใน setState */
  assert.doesNotMatch(
    code,
    /let\s+next\s*=\s*null[\s\S]{0,200}setState\(\s*\(/,
    "กลับไปใช้รูปที่เคยพัง — ค่าที่ส่งจะเป็น null เพราะ React ยังไม่ได้เรียกฟังก์ชันนั้น",
  );
});

test("★ ค่าจริงต้องเก็บใน ref เพื่อคิดค่าใหม่ได้ทันที", () => {
  assert.match(src, /useRef/, "ต้องมี ref เก็บค่าจริง");
  assert.match(src, /kinds\.current/, "toggle ต้องคิดค่าใหม่จาก ref ไม่ใช่จาก state");
});

test("★★ คำขอต้องต่อคิว ไม่ยิงพร้อมกัน (บั๊กเดียวกับ T1.351)", () => {
  /* ติ๊กสามช่องเร็ว ๆ แล้วยิงพร้อมกัน ตัวที่ตอบช้าสุดจะเขียนทับตัวอื่น
     ช่องที่ติ๊กทีหลังหายเงียบ — ตู้กลางเคยเจอมาแล้ว */
  assert.match(src, /queue\.current\s*=\s*queue\.current/, "ต้องต่อคิวคำขอตามลำดับที่กด");
});

test("★ ล้มแล้วต้องไปถามค่าจริงจากเซิร์ฟเวอร์ ไม่เดาย้อนเอง", () => {
  const fail = src.slice(src.indexOf(".catch((err)"), src.indexOf("return queue.current"));
  assert.match(fail, /apiGet\("\/activity\/settings"\)/,
    "เดาย้อนเองตอนมีหลายคำขอค้าง จะย้อนผิดตัวแล้วหน้าจอไม่ตรงกับของจริง");
});
