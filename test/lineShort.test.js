/**
 * ไลน์ตอบคำถามสั้นได้เอง ไม่ต้องส่งไปให้ AI (T1.324)
 *
 * วัดของจริงก่อนทำ: คำถามสั้นที่คนหน้าฟาร์มพิมพ์ **13 จาก 20 คำถามตกไปหา AI**
 * ทั้งที่เราตอบเองได้ทันทีจากข้อมูลของเรา และบางคำถาม AI ตอบว่า "ต้องไปถามในเว็บ"
 * ซึ่งแย่กว่าตอบเองหลายเท่าเพราะเรามีคำตอบอยู่ในมือแล้ว
 */
import test from "node:test";
import assert from "node:assert/strict";

import { detectIntent, detectRecord } from "../server/src/line/intent.js";
import { ASK_WHICH, powerText } from "../server/src/line/recordText.js";

/* ---------- คำถามสั้นต้องเข้าทางของเราเอง ---------- */

test("★ คำถามสั้นเรื่องสภาพเล้าต้องได้การ์ดสภาพแวดล้อม", () => {
  /* "สบายดีไหม" ของเล้า = การ์ดสภาพแวดล้อม ซึ่งมีทั้งค่าและคำแนะนำอยู่แล้ว */
  for (const q of ["ปกติไหม", "โอเคไหม", "เรียบร้อยไหม", "ดีไหม", "ตอนนี้เป็นไง", "วันนี้เป็นไง", "ลมแรงไหม"]) {
    assert.equal(detectIntent(q), "env", q);
  }
});

test("ถามจำนวนสั้น ๆ ต้องได้คำตอบเรื่องสุกร", () => {
  for (const q of ["กี่ตัว", "หมูกี่ตัว", "จำนวนตัว"]) assert.equal(detectIntent(q), "pigs", q);
});

test("ถามเรื่องไฟต้องเข้าทางค่าไฟ", () => {
  for (const q of ["ค่าไฟเท่าไร", "ไฟใช้เท่าไร", "กำลังไฟ", "แรงดัน", "หน่วยไฟ", "kwh"]) {
    assert.equal(detectIntent(q), "power", q);
  }
});

test("★ สั้นจนไม่รู้ว่าถามอะไร ต้องถามกลับ ไม่เดา", () => {
  /* เดาผิดแพงกว่าถามกลับหนึ่งที เพราะคนจะเอาเลขที่ไม่ได้ถามไปใช้ */
  for (const q of ["เท่าไร", "เท่าไหร่", "ไหน", "อะไร", "เล้าไหน"]) assert.equal(detectIntent(q), "ambiguous", q);
  /* ★ แต่คำเดียวกันที่อยู่ในประโยคอื่นต้องไม่ถูกจับ — ไม่งั้นคำถามที่ควรส่งให้ AI จะได้เมนูแทน */
  assert.equal(detectIntent("พรุ่งนี้หวยออกอะไร"), "unknown");
  assert.equal(detectIntent("ควรทำอะไรต่อ"), "unknown");
  /* และต้องเสนอตัวเลือกให้ ไม่ใช่ถามลอย ๆ */
  assert.match(ASK_WHICH, /อุณหภูมิ/);
  assert.match(ASK_WHICH, /ค่าไฟ/);
});

test("★★ คำเจาะจงต้องชนะคำกำกวม", () => {
  /* "อุณหภูมิเท่าไร" มีคำว่า "เท่าไร" อยู่ด้วย ถ้าคำกำกวมชนะ จะกลายเป็นถามกลับ
     ทั้งที่คนบอกชัดแล้วว่าถามอุณหภูมิ — ลำดับในตารางคำจึงสำคัญ */
  assert.equal(detectIntent("อุณหภูมิเท่าไร"), "temp");
  assert.equal(detectIntent("ความชื้นเท่าไร"), "humidity");
  assert.equal(detectIntent("ค่าไฟเท่าไร"), "power");
  assert.equal(detectIntent("หมูกี่ตัว"), "pigs");
});

test("★★ คำสั่งบันทึกต้องไม่ถูกคำถามสั้นกลืน", () => {
  /* "ตาย 1 ตัว" มีคำว่า "ตัว" และ "ย้ายเข้า 500 ตัว" ก็มี
     ถ้าคำถามสั้นมาชนะ การบันทึกจะกลายเป็นคำถาม แล้วข้อมูลหายไปเงียบ ๆ */
  for (const [q, type] of [["ตาย 1 ตัว", "dead"], ["ย้ายเข้า 500 ตัว", "moveIn"], ["ให้อาหาร 200", "feed"]]) {
    assert.equal(detectRecord(q)?.type, type, q);
  }
});

/* ---------- ข้อความค่าไฟ ---------- */

const READING = {
  voltage: 226.02, current_a: 4.49, current_b: 4.88, current_c: 5.43,
  frequency: 50.02, power_kw: 2.95,
  today_kwh: 53.4, month_kwh: 412.8, today_from: "2026-10-08T00:17:00+07:00",
};

test("★★ ห้ามบวกกระแสสามเฟสเข้าด้วยกัน", () => {
  /* ต่างเฟสกัน 120° บวกเลขตรง ๆ ไม่มีความหมาย (กติกาเดียวกับหน้าเว็บ)
     ถ้าใครเผลอรวมจะได้ 14.8 A ซึ่งเป็นเลขที่ไม่มีอยู่จริง */
  const t = powerText(READING, "โรงเรือน A1");
  assert.match(t, /4\.5 \/ 4\.9 \/ 5\.4 A/);
  assert.ok(!t.includes("14.8"), "ต้องไม่มีผลรวมของสามเฟส");
});

test("ค่าหลักต้องอยู่ครบและปัดทศนิยมเดียว", () => {
  const t = powerText(READING, "โรงเรือน A1");
  assert.match(t, /กำลังไฟ 3\.0 kW/);
  assert.match(t, /226\.0 V/);
  assert.match(t, /50\.0 Hz/);
  assert.match(t, /ใช้ไปวันนี้ 53\.4 หน่วย/);
  assert.match(t, /เดือนนี้ 412\.8 หน่วย/);
});

test("★ ต้องบอกเวลาที่เริ่มนับของวันนี้", () => {
  /* ถ้าเริ่มเก็บตอนสาย ตัวเลข "วันนี้" ไม่ครอบคลุมทั้งวัน
     ไม่บอกแล้วคนอ่านจะนึกว่าฟาร์มใช้ไฟแค่นั้นจริง ๆ */
  assert.match(powerText(READING, "A1"), /เริ่มนับ/);
});

test("★ ไม่แปลงเป็นบาท เพราะยังไม่ได้ตั้งค่าไฟต่อหน่วย", () => {
  /* เลขบาทที่คิดจากอัตราสมมติดูน่าเชื่อแต่ผิด ซึ่งแย่กว่าไม่บอก */
  const t = powerText(READING, "A1");
  assert.ok(!t.includes("บาท"), "ห้ามมีหน่วยบาทจนกว่าจะตั้งอัตราจริง");
});

test("ไม่มีค่าจากมิเตอร์ ต้องบอกตรง ๆ ไม่ขึ้นขีดกลางเปล่า ๆ", () => {
  assert.match(powerText(null, "โรงเรือน A1"), /ยังไม่มีค่าจากมิเตอร์/);
});

test("ค่าที่หายบางตัวต้องไม่ทำให้ข้อความพัง", () => {
  const t = powerText({ voltage: 226, power_kw: null, current_a: null, current_b: null, current_c: null }, "A1");
  assert.match(t, /กำลังไฟ —/);
  assert.ok(!t.includes("กระแสแต่ละเฟส"), "ไม่มีกระแสเลยก็ไม่ต้องขึ้นบรรทัดนั้น");
});
