/**
 * คำถามนี้ "ใครควรตอบ" (T1.282) — ผู้ใช้แจ้ง 24 ก.ย. 2569 ว่าวอยซ์ตอบไม่ตรงประเด็น
 *
 * ต้นเหตุที่เจอตอนไล่คำถามจริงทีละข้อ: คำที่ใช้จับเรื่อง `farms` มีคำว่า "หมู"/"สุกร"
 * ซึ่งติดแทบทุกประโยคในแดชบอร์ดหมู คำถามเชิงความรู้จึงถูกตอบด้วยสถิติฟาร์ม
 * และทางลัด `LOCAL_ONLY_TOPICS` ทำงาน**ก่อน**ตัวกันคำถามขอความเห็น ทั้งที่ทางสายล่างมีตัวกัน
 *
 * เทสต์นี้คุม "ใครได้คำถามไป" ไม่ได้คุมเนื้อคำตอบ — เนื้อคำตอบเป็นของ AI ที่เราไม่ได้คุม
 */
import test from "node:test";
import assert from "node:assert/strict";

import { localOnlyTopicFor, wantsAdvice } from "../src/components/assistant/answers.js";
import { currentReadingAsk } from "../src/lib/api/sensorQuestion.js";

/* ---------- ความรู้เรื่องหมู ต้องไม่ถูกตอบด้วยสถิติฟาร์ม ---------- */

test("คำถามความรู้เรื่องหมู ต้องไม่ถูกคำตอบสำเร็จรูปเรื่องฟาร์มฉกไป", () => {
  /* ของจริงที่เจอ: ถามเรื่องสายพันธุ์ แล้วได้จำนวนฟาร์มกลับมา */
  for (const q of [
    "หมูสายพันธุ์ดูร็อคเลี้ยงยังไง",
    "สุกรพันธุ์ลาร์จไวท์ต่างจากแลนด์เรซยังไง",
    "ทำไมหมูถึงไอ",
    "หมูท้องเสียทำยังไงดี",
  ]) {
    assert.equal(localOnlyTopicFor(q), null, `"${q}" ไม่ควรถูกตอบจากในเครื่องอย่างเดียว`);
  }
});

test("บันทึกหมูป่วยอยู่ฝั่ง Farmy ไม่ได้อยู่กับเรา — ต้องปล่อยให้เขาตอบ", () => {
  assert.equal(localOnlyTopicFor("หมูป่วยกี่ตัว"), null);
  assert.equal(localOnlyTopicFor("วันนี้มีหมูป่วยเพิ่มไหม"), null);
});

/* ---------- แต่ต้องไม่แก้จนเกินเลย ---------- */

test("เรื่องที่มีแต่เครื่องนี้รู้ ต้องยังตอบเองแม้ถามเชิงความเห็น", () => {
  /* AI ข้างนอกไม่มีทางรู้ว่าโรงเรือนไหนของเรามีแจ้งเตือนค้างกี่อัน
     ตัวกันคำถามขอความเห็นจึงใช้เฉพาะเรื่องที่คำจับกว้าง (`farms`) ไม่ใช่ทุกเรื่อง */
  assert.ok(wantsAdvice("ควรดูแจ้งเตือนไหนก่อน"), "ประโยคนี้ต้องนับเป็นคำถามขอความเห็น");
  assert.equal(localOnlyTopicFor("ควรดูแจ้งเตือนไหนก่อน"), "alerts");
  assert.equal(localOnlyTopicFor("มีแจ้งเตือนอะไรบ้าง"), "alerts");
});

/* ---------- ค่าที่วัดได้ตอบได้แค่ "ตอนนี้" ---------- */

test("คำถามถึงอนาคต ต้องไม่ถูกตอบด้วยค่าเซนเซอร์ตอนนี้", () => {
  /* ของจริงที่เจอ: "อากาศพรุ่งนี้เป็นยังไง" ได้ค่าที่วัดได้ตอนนี้กลับมา
     ซึ่งไม่ใช่คำตอบของคำถามนั้นเลย — ตัวกันเดิมมีแต่คำว่า "พยากรณ์" */
  for (const q of [
    "อากาศพรุ่งนี้เป็นยังไง",
    "คืนนี้อุณหภูมิจะลงไหม",
    "สัปดาห์หน้าอากาศเป็นยังไง",
  ]) {
    assert.equal(currentReadingAsk(q), null, `"${q}" ไม่ใช่คำถามขอค่าปัจจุบัน`);
    assert.equal(localOnlyTopicFor(q), null, `"${q}" ต้องไม่ถูกตอบจากในเครื่องอย่างเดียว`);
  }
});

test("ถามค่าตอนนี้ต้องยังได้ค่าจากเซนเซอร์เหมือนเดิม", () => {
  /* กันแก้จนเกินเลย — ทางนี้เร็วกว่า AI ราวพันเท่า (0.1 วินาที เทียบกับ 28–150 วินาที) */
  assert.deepEqual(currentReadingAsk("ตอนนี้อุณหภูมิเท่าไหร่"), ["temp_c"]);
  assert.deepEqual(currentReadingAsk("ความชื้นเท่าไหร่"), ["humidity"]);
});
