-- ─────────────────────────────────────────────────────────────────────────
--  obs = ค่าที่ "สังเกตได้จริง" ณ เวลานั้น
--
--  เก็บเป็นรูปยาว (หนึ่งแถว = หนึ่งค่า) ไม่ใช่รูปกว้าง เพราะแหล่งข้อมูลแต่ละแหล่ง
--  มีค่าไม่เท่ากันและเพิ่มค่าใหม่ได้ตลอด ถ้าเก็บเป็นคอลัมน์ต้องแก้ตารางทุกครั้ง
--  ที่พี่เขาต่อเซนเซอร์ตัวใหม่ — ซึ่งเป็นเรื่องที่จะเกิดขึ้นแน่ ๆ
--
--  primary key ไม่มี `source` โดยตั้งใจ: หนึ่งจุดเวลาของหนึ่งค่า ต้องมีความจริง
--  เดียวเท่านั้น ถ้าสองแหล่งส่งค่าเดียวกันมา (เช่น PlotNexus กับสำเนาในเครื่อง
--  ซึ่งมาจากเซนเซอร์ตัวเดียวกัน) เก็บของแหล่งแรกที่มาถึงแล้วทิ้งที่เหลือ
--  ไม่งั้นตอน backfill ทีหลังจะได้ข้อมูลซ้อนสองชุดแล้วค่าเฉลี่ยเพี้ยนทั้งชุด
-- ─────────────────────────────────────────────────────────────────────────
create table if not exists obs (
  at       timestamptz      not null,
  station  text             not null references station (id),
  measure  text             not null,
  value    double precision not null,
  source   text             not null,
  primary key (station, measure, at)
);

select create_hypertable('obs', 'at', if_not_exists => true, migrate_data => true);
create index if not exists obs_at_idx on obs (at desc);
create index if not exists obs_lookup_idx on obs (station, measure, at desc);

-- ─────────────────────────────────────────────────────────────────────────
--  fcst = ค่าพยากรณ์ ซึ่ง **มีสองเวลา ไม่ใช่เวลาเดียว**
--
--  ═══ ตารางนี้คือสิ่งที่กันไม่ให้โมเดลโกงตัวเอง ═══
--  ถ้าเก็บพยากรณ์ปนลงตาราง obs แล้วเอาไปเทรน จะเกิด "data leakage":
--  โมเดลได้เห็นค่าที่ ณ เวลาทำนายจริงยังไม่มีใครรู้ ผลคือคะแนนตอนทดสอบสวยมาก
--  แต่พอเอาไปใช้จริงพยากรณ์ไม่ได้เรื่องเลย และหาสาเหตุไม่เจอด้วย
--
--    issued_at = ตอนที่คำพยากรณ์นี้ถูกประกาศออกมา
--    valid_at  = เวลาที่คำพยากรณ์นี้พูดถึง
--
--  ตอนสร้างชุดข้อมูลเทรน ให้เลือกเฉพาะแถวที่ `issued_at <= เวลาที่ทำนาย` เท่านั้น
--  เท่ากับจำลองสถานการณ์จริงว่า ณ ตอนนั้นเรารู้อะไรบ้าง
-- ─────────────────────────────────────────────────────────────────────────
create table if not exists fcst (
  issued_at timestamptz      not null,
  valid_at  timestamptz      not null,
  station   text             not null references station (id),
  measure   text             not null,
  value     double precision,
  source    text             not null,
  primary key (station, measure, valid_at, issued_at)
);

select create_hypertable('fcst', 'valid_at', if_not_exists => true, migrate_data => true);
create index if not exists fcst_issued_idx on fcst (issued_at desc);

-- ─────────────────────────────────────────────────────────────────────────
--  บันทึกทุกรอบที่ไปดึงข้อมูล — สำเร็จหรือล้ม ได้กี่แถว
--
--  **จำเป็นกว่าที่คิด** ข้อมูลที่ขาดหายไปหนึ่งชั่วโมงหน้าตาเหมือนกันหมด
--  ไม่ว่าจะเพราะเน็ตหลุด · เครื่องปิด · หรือเซนเซอร์เสีย แต่สามอย่างนี้
--  ต้องปฏิบัติกับมันคนละแบบตอนทำความสะอาดข้อมูล ตารางนี้เป็นตัวบอกว่าเป็นแบบไหน
-- ─────────────────────────────────────────────────────────────────────────
create table if not exists collect_log (
  id       bigserial primary key,
  at       timestamptz not null default now(),
  source   text        not null,
  ok       boolean     not null,
  rows_in  integer     not null default 0,
  note     text
);
create index if not exists collect_log_at_idx on collect_log (at desc);

