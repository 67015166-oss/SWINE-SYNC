--
--  **ห้ามเอา model ไปปนกับ outdoor** — ค่าจาก Open-Meteo เป็นค่าของ "กริดขนาด
--  หลายกิโลเมตร" ไม่ใช่ค่าที่เสาในฟาร์มวัดได้จริง สองอย่างนี้ต่างกันเป็นองศา
--  และความต่างนั้นเองคือสิ่งที่โมเดลตัวที่สองมีหน้าที่เรียนรู้
-- ─────────────────────────────────────────────────────────────────────────
